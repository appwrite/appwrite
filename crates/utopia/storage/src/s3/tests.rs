//! Memory bounds of S3 transfers: uploads stream from a seekable body,
//! downloads stream as the response arrives.

use std::io;
use std::sync::Arc;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::Duration;

use async_trait::async_trait;
use bytes::Bytes;
use futures_util::StreamExt;
use utopia_async::io::{AsyncReadExt, AsyncWriteExt};
use utopia_async::net::{TcpListener, TcpStream};

use super::*;
use crate::Source;

const LARGE: usize = 64 << 20;

/// The byte at `position` of a generated body.
fn pattern(position: usize) -> u8 {
    (position % 251) as u8
}

/// Bytes handed out by a [`Generated`] body and not dropped yet, and the
/// most there ever were at once.
#[derive(Default)]
struct Live {
    current: AtomicUsize,
    peak: AtomicUsize,
}

impl Live {
    fn peak(&self) -> usize {
        self.peak.load(Ordering::SeqCst)
    }
}

/// A chunk that counts as live until it is dropped.
struct Tracked {
    data: Vec<u8>,
    live: Arc<Live>,
}

impl AsRef<[u8]> for Tracked {
    fn as_ref(&self) -> &[u8] {
        &self.data
    }
}

impl Drop for Tracked {
    fn drop(&mut self) {
        self.live.current.fetch_sub(self.data.len(), Ordering::SeqCst);
    }
}

/// A seekable body of `size` generated bytes, made a chunk at a time.
struct Generated {
    size: usize,
    position: usize,
    live: Arc<Live>,
}

impl Generated {
    fn body(size: usize, live: &Arc<Live>) -> Body {
        Body::new(Generated { size, position: 0, live: live.clone() })
    }
}

#[async_trait]
impl Source for Generated {
    async fn read(&mut self, max: usize) -> io::Result<Bytes> {
        let end = self.size.min(self.position + max);
        let data: Vec<u8> = (self.position..end).map(pattern).collect();
        self.position = end;
        let current = self.live.current.fetch_add(data.len(), Ordering::SeqCst) + data.len();
        self.live.peak.fetch_max(current, Ordering::SeqCst);
        Ok(Bytes::from_owner(Tracked { data, live: self.live.clone() }))
    }

    fn is_seekable(&self) -> bool {
        true
    }

    async fn rewind(&mut self) -> io::Result<()> {
        self.position = 0;
        Ok(())
    }
}

/// Reads each request's payload chunk by chunk, checking it against the
/// pattern. The first attempt gives up halfway and answers 503, so the
/// retry has to send the payload again from its start.
#[derive(Default)]
struct Draining {
    attempts: AtomicUsize,
    received: std::sync::Mutex<Vec<usize>>,
}

#[async_trait]
impl Client for Draining {
    async fn send(&self, request: &Request) -> std::result::Result<Response, TransportError> {
        let attempt = self.attempts.fetch_add(1, Ordering::SeqCst) + 1;
        let length: usize = request.header("content-length").unwrap_or_default().parse().unwrap_or_default();
        let mut chunks = request.body.chunks();
        let mut received = 0;
        while let Some(chunk) = chunks.next().await {
            let chunk = chunk.map_err(|e| TransportError::Network { message: e.to_string(), code: 0 })?;
            assert!(chunk.iter().enumerate().all(|(i, b)| *b == pattern(received + i)), "bytes out of order");
            received += chunk.len();
            if attempt == 1 && received >= length / 2 {
                break;
            }
        }
        self.received.lock().unwrap().push(received);
        Ok(match attempt {
            1 => Response::new(503),
            _ => Response::new(200).with_header("ETag", "\"etag\""),
        })
    }
}

#[utopia_async::test]
async fn an_upload_streams_its_body_and_resends_it_on_a_retry() {
    let live = Arc::new(Live::default());
    let client = Arc::new(Draining::default());
    let device = S3::new("root", "key", "secret", "https://s3.example.com", "us-east-1")
        .unwrap()
        .with_client(Retry::new(client.clone(), RetryStrategy::new(3, 0.0, 0.0)));

    let etag = device.write("root/large.bin", Generated::body(LARGE, &live), "application/octet-stream").await.unwrap();

    assert_eq!(etag, "etag");
    assert_eq!(*client.received.lock().unwrap(), vec![LARGE / 2, LARGE]);
    // The hashing pass holds the first chunk while it reads the second.
    assert!(live.peak() <= 2 * client::CHUNK_SIZE, "{} bytes in memory at once", live.peak());
    eprintln!("upload of {LARGE} bytes through a draining client: peak {} bytes in memory", live.peak());
}

#[utopia_async::test]
async fn a_small_upload_is_sent_from_memory() {
    let client = Arc::new(Draining::default());
    client.attempts.store(1, Ordering::SeqCst);
    let device = S3::new("root", "key", "secret", "https://s3.example.com", "us-east-1").unwrap().with_client(client);
    let live = Arc::new(Live::default());

    device.write("root/small.bin", Generated::body(1000, &live), "").await.unwrap();

    // Read once to hash it, and not again to send it.
    assert_eq!(live.peak(), 1000);
}

/// Reads an HTTP/1.1 request head, returning it.
async fn head(socket: &mut TcpStream) -> String {
    let mut head = Vec::new();
    while !head.ends_with(b"\r\n\r\n") {
        head.push(socket.read_u8().await.unwrap());
    }
    String::from_utf8(head).unwrap()
}

#[utopia_async::test]
async fn the_http_client_streams_an_upload() {
    let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
    let address = listener.local_addr().unwrap();
    let server = utopia_async::spawn(async move {
        let (mut socket, _) = listener.accept().await.unwrap();
        let head = head(&mut socket).await.to_ascii_lowercase();
        let length: usize = head
            .lines()
            .find_map(|line| line.strip_prefix("content-length: "))
            .and_then(|value| value.trim().parse().ok())
            .unwrap();
        let mut buffer = vec![0; 1 << 16];
        let mut received = 0;
        while received < length {
            let n = socket.read(&mut buffer).await.unwrap();
            assert!(n > 0, "the connection closed after {received} bytes");
            assert!(buffer[..n].iter().enumerate().all(|(i, b)| *b == pattern(received + i)));
            received += n;
        }
        socket.write_all(b"HTTP/1.1 200 OK\r\nETag: \"etag\"\r\nContent-Length: 0\r\n\r\n").await.unwrap();
        received
    });
    let live = Arc::new(Live::default());
    let device = S3::new("root", "key", "secret", &format!("http://{address}/bucket"), "us-east-1").unwrap();

    let etag = device.write("root/large.bin", Generated::body(LARGE, &live), "").await.unwrap();

    assert_eq!(etag, "etag");
    assert_eq!(server.await.unwrap(), LARGE);
    // A chunk or two waits in hyper's write queue; the body is never whole.
    assert!(live.peak() <= 4 * client::CHUNK_SIZE, "{} bytes in memory at once", live.peak());
    eprintln!("upload of {LARGE} bytes through HttpClient: peak {} bytes in memory", live.peak());
}

#[utopia_async::test]
async fn the_http_client_streams_a_download() {
    const FIRST: usize = 1 << 20;
    const SIZE: usize = 8 << 20;
    let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
    let address = listener.local_addr().unwrap();
    let (proceed, wait) = utopia_async::sync::oneshot::channel::<()>();
    let server = utopia_async::spawn(async move {
        let (mut socket, _) = listener.accept().await.unwrap();
        head(&mut socket).await;
        let data: Vec<u8> = (0..SIZE).map(pattern).collect();
        socket.write_all(format!("HTTP/1.1 200 OK\r\nContent-Length: {SIZE}\r\n\r\n").as_bytes()).await.unwrap();
        socket.write_all(&data[..FIRST]).await.unwrap();
        // The rest is only sent once the reader has seen the first part.
        wait.await.unwrap();
        socket.write_all(&data[FIRST..]).await.unwrap();
    });
    let device = S3::new("root", "key", "secret", &format!("http://{address}/bucket"), "us-east-1").unwrap();

    let mut body = utopia_async::timeout(Duration::from_secs(10), device.read("root/large.bin", 0, None, None))
        .await
        .expect("read() waited for the whole response")
        .unwrap();
    let mut received = 0;
    while received < FIRST {
        let chunk = utopia_async::timeout(Duration::from_secs(10), body.read(1 << 16)).await.unwrap().unwrap();
        assert!(!chunk.is_empty());
        assert!(chunk.iter().enumerate().all(|(i, b)| *b == pattern(received + i)));
        received += chunk.len();
    }
    proceed.send(()).unwrap();
    let rest = body.bytes().await.unwrap();

    assert_eq!(received + rest.len(), SIZE);
    assert!(rest.iter().enumerate().all(|(i, b)| *b == pattern(received + i)));
    server.await.unwrap();
}

#[utopia_async::test]
async fn a_download_rewinds_from_what_it_kept() {
    // Past the 2 MiB kept in memory, so the rest is replayed from a file.
    const SIZE: usize = 8 << 20;
    let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
    let address = listener.local_addr().unwrap();
    utopia_async::spawn(async move {
        let (mut socket, _) = listener.accept().await.unwrap();
        head(&mut socket).await;
        let data: Vec<u8> = (0..SIZE).map(pattern).collect();
        socket.write_all(format!("HTTP/1.1 200 OK\r\nContent-Length: {SIZE}\r\n\r\n").as_bytes()).await.unwrap();
        socket.write_all(&data).await.unwrap();
    });
    let device = S3::new("root", "key", "secret", &format!("http://{address}/bucket"), "us-east-1").unwrap();
    let mut body = device.read("root/large.bin", 0, None, None).await.unwrap();
    assert!(body.is_seekable());

    let mut first = Vec::new();
    while first.len() < 3 << 20 {
        first.extend_from_slice(&body.read(1 << 20).await.unwrap());
    }
    body.rewind().await.unwrap();
    let whole = body.bytes().await.unwrap();

    assert_eq!(whole.len(), SIZE);
    assert!(whole.iter().enumerate().all(|(i, b)| *b == pattern(i)));
}

#[utopia_async::test]
async fn the_http_client_reads_a_streamed_error() {
    let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
    let address = listener.local_addr().unwrap();
    utopia_async::spawn(async move {
        let (mut socket, _) = listener.accept().await.unwrap();
        head(&mut socket).await;
        let body = "<?xml version=\"1.0\"?><Error><Code>NoSuchKey</Code><Message>Gone.</Message></Error>";
        let response = format!("HTTP/1.1 404 Not Found\r\nContent-Length: {}\r\n\r\n{body}", body.len());
        socket.write_all(response.as_bytes()).await.unwrap();
    });
    let device = S3::new("root", "key", "secret", &format!("http://{address}/bucket"), "us-east-1").unwrap();

    let error = device.read("root/missing.bin", 0, None, None).await.unwrap_err();

    assert!(error.is_not_found());
    assert_eq!(error.to_string(), "Gone.");
}
