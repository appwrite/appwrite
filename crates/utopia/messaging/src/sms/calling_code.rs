/// The calling code a phone number starts with, longest match first, after
/// dropping `+`, spaces, parentheses and dashes, and an international
/// prefix (`00` or `011`).
///
/// PHP: `CallingCode::fromPhoneNumber()`.
pub fn from_phone_number(number: &str) -> Option<&'static str> {
    let digits: String = number.chars().filter(|c| !matches!(c, '+' | ' ' | '(' | ')' | '-')).collect();
    let digits = digits.strip_prefix("00").or_else(|| digits.strip_prefix("011")).unwrap_or(&digits);
    for length in [3, 2, 1] {
        let code = php_std::string::substr(digits.as_bytes(), 0, Some(length));
        if let Some(found) = std::str::from_utf8(code).ok().and_then(known) {
            return Some(found);
        }
    }
    None
}
