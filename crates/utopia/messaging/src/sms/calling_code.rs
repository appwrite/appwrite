/// The calling code a phone number starts with, longest match first, after
/// dropping `+`, spaces, parentheses and dashes, and an international
/// prefix (`00` or `011`).
///
/// PHP: `CallingCode::fromPhoneNumber()`.
pub fn from_phone_number(number: &str) -> Option<&'static str> {
    // Only the first six kept bytes matter: a prefix of up to three, then a
    // code of up to three.
    let mut kept = [0u8; 6];
    let mut len = 0;
    for &b in number.as_bytes() {
        if matches!(b, b'+' | b' ' | b'(' | b')' | b'-') {
            continue;
        }
        kept[len] = b;
        len += 1;
        if len == kept.len() {
            break;
        }
    }
    let kept = &kept[..len];
    let digits = kept.strip_prefix(b"00").or_else(|| kept.strip_prefix(b"011")).unwrap_or(kept);
    [3, 2, 1].into_iter().find_map(|length| known(&digits[..length.min(digits.len())]))
}
