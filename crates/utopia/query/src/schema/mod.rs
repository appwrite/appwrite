//! Schema builders: DDL for tables, columns, indexes, views, procedures and
//! triggers, per dialect.
//!
//! A schema ([`MySql`], [`PostgreSql`], [`Sqlite`], [`ClickHouse`],
//! [`MongoDb`]) compiles statements; [`Schema::table`] starts a fluent
//! [`Table`] blueprint whose terminal methods ([`Table::create`],
//! [`Table::alter`], [`Table::drop`], ...) compile it. Each dialect only has
//! the column and table methods it can express (marker traits in
//! [`column`](mod@column) and [`table`]), and the statements beyond tables are
//! capability traits in [`feature`].
//!
//! ```
//! use utopia_query::schema::{ForeignKeyAction, PostgreSql, Schema};
//!
//! let mut posts = PostgreSql::new().table("posts");
//! posts.id("id");
//! posts.string("title", 120);
//! posts.integer("author_id");
//! posts.foreign_key("author_id").references("id").on("users").on_delete(ForeignKeyAction::Cascade);
//! assert_eq!(
//!     posts.create()?.query,
//!     "CREATE TABLE \"posts\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, \
//!      \"title\" VARCHAR(120) NOT NULL, \"author_id\" INTEGER NOT NULL, PRIMARY KEY (\"id\"), \
//!      FOREIGN KEY (\"author_id\") REFERENCES \"users\" (\"id\") ON DELETE CASCADE)"
//! );
//! # Ok::<(), utopia_query::Error>(())
//! ```
//!
//! ```php
//! use Utopia\Query\Schema\ForeignKeyAction;
//! use Utopia\Query\Schema\PostgreSQL;
//!
//! $posts = (new PostgreSQL())->table('posts');
//! $posts->id();
//! $posts->string('title', 120);
//! $posts->integer('author_id');
//! $posts->foreignKey('author_id')->references('id')->on('users')->onDelete(ForeignKeyAction::Cascade);
//! echo $posts->create()->query, "\n";
//! ```
//!
//! PHP: `Utopia\Query\Schema`, `Utopia\Query\Schema\*`.
//!
//! | PHP | Rust |
//! |---|---|
//! | `Schema` (abstract), `Schema\SQL` | [`Schema`] (trait) |
//! | `Schema\MySQL`, `PostgreSQL`, `SQLite`, `ClickHouse`, `MongoDB` | [`MySql`], [`PostgreSql`], [`Sqlite`], [`ClickHouse`], [`MongoDb`] |
//! | `Schema\Table`, `Table\*` | [`Table`] (`Table<MySql>`, ...), [`TableDefinition`] (its properties) |
//! | `Table\Trait\*` | marker traits in [`table`] ([`table::Serial`], [`table::Checks`], ...) |
//! | `Schema\Column`, `Column\*` | [`Column`] (`Column<MySql>`, ...), [`ColumnDefinition`] (its properties) |
//! | `Column\Trait\*` | marker traits in [`column`](mod@column) ([`column::Unique`], [`column::Collation`], ...) |
//! | `Schema\ForeignKey`, `ForeignKey\*` | [`ForeignKey`] |
//! | `Schema\Forwarder\*` | none: a column or key handle borrows its table, so table methods are called on the table |
//! | `Schema\Index`, `CheckConstraint`, `RenameColumn` | [`Index`], [`CheckConstraint`], [`RenameColumn`] |
//! | `createIndex()` options | [`IndexOptions`] |
//! | `Schema\Feature\*` | traits in [`feature`] |
//! | `Schema\Trait\*` | the dialects' implementations of those traits |
//! | `ColumnType`, `IndexType`, `ForeignKeyAction`, `Order`, `ParameterDirection`, `PartitionType`, `TriggerEvent`, `TriggerTiming` | [`ColumnType`], [`IndexType`], [`ForeignKeyAction`], [`Order`], [`ParameterDirection`], [`PartitionType`], [`TriggerEvent`], [`TriggerTiming`] |
//! | `Schema\ClickHouse\Engine`, `ClickHouse\IndexAlgorithm` | [`Engine`], [`IndexAlgorithm`] |

