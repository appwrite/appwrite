/// A dialect's DDL compiler: quoting, column types, and the table, index
/// and drop statements. Dialects override the steps they write
/// differently; the provided methods are the shared (MySQL-flavoured)
/// compilation.
///
/// Implement it (and the [`feature`] traits) to add a dialect.
///
/// PHP: the abstract `Utopia\Query\Schema`.
pub trait Schema: Clone + Send + Sync + Sized + 'static {
    /// The executor statements carry, if any.
    fn executor(&self) -> Option<&Executor>;

    /// Sets the executor every statement compiled from now on carries
    /// ([`Statement::execute`] runs it).
    ///
    /// PHP: `setExecutor()`.
    fn set_executor(&mut self, executor: Executor) -> &mut Self;

    /// Quotes a possibly qualified identifier.
    ///
    /// PHP: `quote()`.
    fn quote(&self, identifier: &str) -> Result<String>;

    /// Quotes one identifier, dots included.
    ///
    /// PHP: `quoteLiteral()`.
    fn quote_literal(&self, identifier: &str) -> Result<String>;

    /// The SQL type of `column`.
    ///
    /// PHP: `compileColumnType()`.
    fn compile_column_type(&self, column: &Column<Self>) -> Result<String>;

    /// The auto-increment keyword.
    ///
    /// PHP: `compileAutoIncrement()`.
    fn compile_auto_increment(&self) -> &'static str;

    /// A blueprint of table `name` compiled by this schema.
    ///
    /// PHP: `table()`.
    fn table(&self, name: impl Into<String>) -> Table<Self> {
        Table::with_schema(self.clone(), name)
    }

    /// `CREATE TABLE [IF NOT EXISTS]` for `table`.
    ///
    /// PHP: `compileCreate()`.
    fn compile_create(&self, table: &Table<Self>, if_not_exists: bool) -> Result<Statement> {
        base::create(self, table, if_not_exists)
    }

    /// `ALTER TABLE` for `table`.
    ///
    /// PHP: `compileAlter()`.
    fn compile_alter(&self, table: &Table<Self>) -> Result<Statement> {
        base::alter(self, table)
    }

    /// `DROP TABLE [IF EXISTS] name`.
    ///
    /// PHP: `compileDrop()`.
    fn compile_drop(&self, name: &str, if_exists: bool) -> Result<Statement> {
        base::plain(self, format!("DROP TABLE {}{}", if if_exists { "IF EXISTS " } else { "" }, self.quote(name)?))
    }

    /// Renames table `from` to `to`.
    ///
    /// PHP: `compileRename()`.
    fn compile_rename(&self, from: &str, to: &str) -> Result<Statement> {
        base::plain(self, format!("RENAME TABLE {} TO {}", self.quote(from)?, self.quote(to)?))
    }

    /// Empties table `name`.
    ///
    /// PHP: `compileTruncate()`.
    fn compile_truncate(&self, name: &str) -> Result<Statement> {
        base::plain(self, format!("TRUNCATE TABLE {}", self.quote(name)?))
    }

    /// `CREATE INDEX name ON table (columns)` with `options`.
    ///
    /// PHP: `createIndex()`.
    fn create_index(&self, table: &str, name: &str, columns: &[&str], options: &IndexOptions) -> Result<Statement> {
        base::create_index(self, table, name, columns, options)
    }

    /// Drops index `name` of `table`.
    ///
    /// PHP: `dropIndex()`.
    fn drop_index(&self, table: &str, name: &str) -> Result<Statement> {
        base::plain(self, format!("DROP INDEX {} ON {}", self.quote(name)?, self.quote(table)?))
    }

    /// The definition of `column` in `CREATE` / `ALTER TABLE`.
    ///
    /// PHP: `compileColumnDefinition()`.
    fn compile_column_definition(&self, column: &Column<Self>) -> Result<String> {
        base::column_definition(self, column)
    }

    /// `GENERATED ALWAYS AS (...) STORED|VIRTUAL`.
    ///
    /// PHP: `compileGeneratedClause()`.
    fn compile_generated_clause(&self, column: &Column<Self>) -> String {
        base::generated_clause(column)
    }

    /// Clauses after the column list of `CREATE TABLE` (partitioning).
    ///
    /// PHP: `compileCreateSuffix()`.
    fn compile_create_suffix(&self, _table: &Table<Self>) -> String {
        String::new()
    }

    /// A collation name as `COLLATE` takes it.
    ///
    /// PHP: `quoteCollation()`.
    fn quote_collation(&self, collation: &str) -> Result<String> {
        Ok(collation.to_owned())
    }

    /// The unsigned keyword, or empty where there is none.
    ///
    /// PHP: `compileUnsigned()`.
    fn compile_unsigned(&self) -> &'static str {
        "UNSIGNED"
    }

    /// The column list of an index: lengths, collations, operator class,
    /// orders and raw expressions.
    ///
    /// PHP: `compileIndexColumns()`.
    fn compile_index_columns(&self, index: &Index) -> Result<String> {
        base::index_columns(self, index)
    }
}
