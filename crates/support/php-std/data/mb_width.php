<?php

// Writes src/mb/width.rs to stdout: the code points mb_strwidth() counts two
// columns wide, as ranges.
//
//   docker run --rm -v "$PWD:/w" -w /w --entrypoint php appwrite-dev \
//       crates/support/php-std/data/mb_width.php > crates/support/php-std/src/mb/width.rs

$ranges = [];
$start = null;
for ($cp = 0; $cp <= 0x110000; $cp++) {
    $wide = $cp <= 0x10FFFF && !($cp >= 0xD800 && $cp <= 0xDFFF) && mb_strwidth(mb_chr($cp, 'UTF-8'), 'UTF-8') === 2;
    if ($wide) {
        $start ??= $cp;
    } elseif ($start !== null) {
        $ranges[] = sprintf('(0x%X, 0x%X),', $start, $cp - 1);
        $start = null;
    }
}

echo "//! The code points mbstring counts two columns wide (`mb_strwidth`,\n";
echo "//! `mb_strimwidth`): its East Asian Width table, as `(first, last)`\n";
echo "//! ranges.\n";
echo "//!\n";
echo "//! Generated by dumping `mb_strwidth(mb_chr(\$cp))` for every code point on\n";
echo "//! the dev image's PHP 8.5.10 (`data/mb_width.php`).\n";
echo "\n";
echo "/// The two-column ranges.\n";
echo "pub(super) const WIDE: &[(u32, u32)] = &[\n";
$line = '   ';
foreach ($ranges as $range) {
    if (strlen($line) + strlen($range) + 1 > 100) {
        echo $line, "\n";
        $line = '   ';
    }
    $line .= ' ' . $range;
}
if (trim($line) !== '') {
    echo $line, "\n";
}
echo "];\n";
