<?php

// Writes src/glob/classes.rs to stdout: for each character class of a glob,
// the code points PHP's fnmatch() (musl's, in the dev image's C.UTF-8 locale)
// matches against `[[:<class>:]]`, as ranges.
//
//   docker run --rm -v "$PWD:/w" -w /w --entrypoint php appwrite-dev \
//       crates/support/php-std/data/glob_classes.php > crates/support/php-std/src/glob/classes.rs

$classes = ['alnum', 'alpha', 'blank', 'cntrl', 'digit', 'graph', 'lower', 'print', 'punct', 'space', 'upper', 'xdigit'];

echo "//! The code points musl puts in each `[:class:]` of a glob in a UTF-8\n";
echo "//! locale, as `(first, last)` ranges.\n";
echo "//!\n";
echo "//! Generated by dumping, for every code point, whether PHP's `fnmatch()`\n";
echo "//! on the dev image (Alpine, musl, `C.UTF-8`) matches it against\n";
echo "//! `[[:<class>:]]` (`data/glob_classes.php`).\n";

foreach ($classes as $class) {
    $pattern = "[[:{$class}:]]";
    $ranges = [];
    $start = null;
    for ($cp = 1; $cp <= 0x110000; $cp++) {
        $in = $cp <= 0x10FFFF && !($cp >= 0xD800 && $cp <= 0xDFFF) && fnmatch($pattern, mb_chr($cp, 'UTF-8'));
        if ($in) {
            $start ??= $cp;
        } elseif ($start !== null) {
            $ranges[] = sprintf('(0x%X, 0x%X),', $start, $cp - 1);
            $start = null;
        }
    }

    echo "\n/// `[:{$class}:]`.\n";
    echo 'pub(super) const ' . strtoupper($class) . ": &[(u32, u32)] = &[\n";
    $line = '   ';
    foreach ($ranges as $range) {
        if (strlen($line) + strlen($range) + 1 > 100) {
            echo $line, "\n";
            $line = '   ';
        }
        $line .= ' ' . $range;
    }
    if (trim($line) !== '') {
        echo $line, "\n";
    }
    echo "];\n";
}
