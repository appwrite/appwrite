const BASE64: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

/// PHP `base64_encode`: standard alphabet with `=` padding.
pub fn base64_encode(s: &[u8]) -> String {
    let mut out = String::with_capacity(s.len().div_ceil(3) * 4);
    for chunk in s.chunks(3) {
        let b = [chunk[0], *chunk.get(1).unwrap_or(&0), *chunk.get(2).unwrap_or(&0)];
        out.push(BASE64[(b[0] >> 2) as usize] as char);
        out.push(BASE64[(((b[0] & 0x03) << 4) | (b[1] >> 4)) as usize] as char);
        out.push(if chunk.len() > 1 { BASE64[(((b[1] & 0x0f) << 2) | (b[2] >> 6)) as usize] as char } else { '=' });
        out.push(if chunk.len() > 2 { BASE64[(b[2] & 0x3f) as usize] as char } else { '=' });
    }
    out
}

/// `base64_reverse_table`: a value, -1 for skipped white space, -2 otherwise.
fn base64_value(c: u8) -> i32 {
    match c {
        b'A'..=b'Z' => (c - b'A') as i32,
        b'a'..=b'z' => (c - b'a') as i32 + 26,
        b'0'..=b'9' => (c - b'0') as i32 + 52,
        b'+' => 62,
        b'/' => 63,
        b'\t' | b'\n' | b'\r' | b' ' => -1,
        _ => -2,
    }
}

/// PHP `base64_decode($string, $strict)`. Non-strict skips every byte that
/// is not in the alphabet (and decodes data after `=` padding); strict skips
/// only `\t \n \r` and spaces and fails (`None`, PHP's `false`) on anything
/// else, on data after padding, on a lone final character or on bad padding.
pub fn base64_decode(s: &[u8], strict: bool) -> Option<Vec<u8>> {
    let mut out: Vec<u8> = Vec::with_capacity(s.len() / 4 * 3 + 3);
    let put = |out: &mut Vec<u8>, j: usize, v: u8, or: bool| {
        if j == out.len() {
            out.push(0);
        }
        if or { out[j] |= v } else { out[j] = v }
    };
    let (mut i, mut padding, mut j) = (0usize, 0usize, 0usize);
    for &c in s {
        if c == b'=' {
            padding += 1;
            continue;
        }
        let ch = base64_value(c);
        if !strict {
            if ch < 0 {
                continue;
            }
        } else {
            if ch == -1 {
                continue;
            }
            if ch == -2 || padding > 0 {
                return None;
            }
        }
        let ch = ch as u8;
        match i % 4 {
            0 => put(&mut out, j, ch << 2, false),
            1 => {
                put(&mut out, j, ch >> 4, true);
                j += 1;
                put(&mut out, j, (ch & 0x0f) << 4, false);
            }
            2 => {
                put(&mut out, j, ch >> 2, true);
                j += 1;
                put(&mut out, j, (ch & 0x03) << 6, false);
            }
            _ => {
                put(&mut out, j, ch, true);
                j += 1;
            }
        }
        i += 1;
    }
    if strict && i % 4 == 1 {
        return None;
    }
    if strict && padding > 0 && (padding > 2 || (i + padding) % 4 != 0) {
        return None;
    }
    out.truncate(j);
    Some(out)
}

/// PHP `bin2hex`: lowercase hexadecimal.
pub fn bin2hex(s: &[u8]) -> String {
    let mut out = String::with_capacity(s.len() * 2);
    for &b in s {
        out.push(HEX_LOWER[(b >> 4) as usize] as char);
        out.push(HEX_LOWER[(b & 15) as usize] as char);
    }
    out
}

/// PHP `hex2bin`: `None` (PHP's `false`, with a warning) for an odd length
/// or a non-hexadecimal character.
pub fn hex2bin(s: &[u8]) -> Option<Vec<u8>> {
    if !s.len().is_multiple_of(2) || !s.iter().all(u8::is_ascii_hexdigit) {
        return None;
    }
    Some(s.chunks(2).map(|p| hex_value(p[0]) * 16 + hex_value(p[1])).collect())
}

