//! Encodings: URL encoding, `http_build_query`, base64, hex, HTML entities,
//! backslash escaping and quoted-printable.
//!
//! Ported from PHP 8.5.10 (`ext/standard/url.c`, `http.c`, `base64.c`,
//! `string.c`, `html.c`, `quot_print.c`). Byte strings in, byte strings out;
//! encoders whose output is always ASCII return `String`.
//!
//! | PHP | Rust |
//! |---|---|
//! | `urlencode`, `rawurlencode`, `urldecode`, `rawurldecode` | [`urlencode`], [`rawurlencode`], [`urldecode`], [`rawurldecode`] |
//! | `http_build_query` | [`http_build_query`] with [`QueryEncoding`] |
//! | `parse_str` | [`parse_str`] |
//! | `base64_encode`, `base64_decode` | [`base64_encode`], [`base64_decode`] |
//! | `bin2hex`, `hex2bin` | [`bin2hex`], [`hex2bin`] |
//! | `htmlspecialchars`, `htmlentities` | [`htmlspecialchars`], [`htmlentities`] with [`HtmlFlags`] |
//! | `htmlspecialchars_decode`, `html_entity_decode` | [`htmlspecialchars_decode`], [`html_entity_decode`] |
//! | `addslashes`, `stripslashes` | [`addslashes`], [`stripslashes`] |
//! | `quoted_printable_encode`, `quoted_printable_decode` | [`quoted_printable_encode`], [`quoted_printable_decode`] |
//!
//! The HTML functions support PHP's default charset, UTF-8. Their entity
//! tables (`encoding/html_tables.rs`) are generated by
//! `data/html_entities.py` from php-src's `ext/standard/html_tables.h` and
//! PHP's own `get_html_translation_table()` (`data/html_entities.php`).
