/// `http_build_query()`'s `$encoding_type`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum QueryEncoding {
    /// `PHP_QUERY_RFC1738` (1, the default): spaces as `+` ([`urlencode`]).
    #[default]
    Rfc1738,
    /// `PHP_QUERY_RFC3986` (2): spaces as `%20` ([`rawurlencode`]).
    Rfc3986,
}

impl QueryEncoding {
    /// PHP's value: 2 is RFC 3986, and every other integer RFC 1738 (PHP
    /// does not validate it).
    pub fn from_php(value: i64) -> Self {
        if value == 2 { QueryEncoding::Rfc3986 } else { QueryEncoding::Rfc1738 }
    }
}

/// Whether a PHP array key string is an integer key (`ZEND_HANDLE_NUMERIC_STR`):
/// `-?[1-9][0-9]*` or `0`, within `i64`.
pub fn is_integer_key(key: &str) -> bool {
    let digits = key.strip_prefix('-').unwrap_or(key);
    if digits.is_empty() || !digits.bytes().all(|b| b.is_ascii_digit()) {
        return false;
    }
    if digits.starts_with('0') && key.len() > 1 {
        return false;
    }
    key.parse::<i64>().is_ok()
}

struct QueryBuilder<'a> {
    out: Vec<u8>,
    separator: &'a [u8],
    raw: bool,
}

impl QueryBuilder<'_> {
    fn scalar(&mut self, key: &str, value: &Value, prefix: Option<&[u8]>, numeric_prefix: Option<&[u8]>) {
        if !self.out.is_empty() {
            self.out.extend_from_slice(self.separator);
        }
        if let Some(p) = prefix {
            self.out.extend_from_slice(p);
        }
        if is_integer_key(key) {
            if let Some(np) = numeric_prefix {
                self.out.extend_from_slice(np);
            }
            self.out.extend_from_slice(key.as_bytes());
        } else {
            url_encode_into(&mut self.out, key.as_bytes(), self.raw);
        }
        if prefix.is_some() {
            self.out.extend_from_slice(b"%5D");
        }
        self.out.push(b'=');
        match value {
            Value::String(s) => url_encode_into(&mut self.out, s.as_bytes(), self.raw),
            Value::Number(n) => match crate::value::json_number(n) {
                crate::value::Number::Int(i) => self.out.extend_from_slice(i.to_string().as_bytes()),
                crate::value::Number::Float(f) => {
                    url_encode_into(&mut self.out, number::to_string(f).as_bytes(), self.raw)
                }
            },
            Value::Bool(b) => self.out.push(if *b { b'1' } else { b'0' }),
            _ => {}
        }
    }

    fn hash(&mut self, data: &Value, prefix: Option<&[u8]>, numeric_prefix: Option<&[u8]>) {
        let entries: Vec<(Cow<'_, str>, &Value)> = match data {
            Value::Array(a) => a.iter().enumerate().map(|(i, v)| (Cow::Owned(i.to_string()), v)).collect(),
            Value::Object(o) => o.iter().map(|(k, v)| (Cow::Borrowed(k.as_str()), v)).collect(),
            _ => return,
        };
        for (key, value) in entries {
            match value {
                Value::Array(_) | Value::Object(_) => {
                    let mut next = Vec::new();
                    if is_integer_key(&key) {
                        match (prefix, numeric_prefix) {
                            (Some(p), Some(np)) => {
                                next.extend_from_slice(p);
                                next.extend_from_slice(np);
                                next.extend_from_slice(key.as_bytes());
                                next.extend_from_slice(b"%5D%5B");
                            }
                            (Some(p), None) => {
                                next.extend_from_slice(p);
                                next.extend_from_slice(key.as_bytes());
                                next.extend_from_slice(b"%5D%5B");
                            }
                            (None, Some(np)) => {
                                next.extend_from_slice(np);
                                next.extend_from_slice(key.as_bytes());
                                next.extend_from_slice(b"%5B");
                            }
                            (None, None) => {
                                next.extend_from_slice(key.as_bytes());
                                next.extend_from_slice(b"%5B");
                            }
                        }
                    } else {
                        let mut encoded = Vec::new();
                        url_encode_into(&mut encoded, key.as_bytes(), self.raw);
                        match prefix {
                            Some(p) => {
                                next.extend_from_slice(p);
                                next.extend_from_slice(&encoded);
                                next.extend_from_slice(b"%5D%5B");
                            }
                            None => {
                                next.extend_from_slice(&encoded);
                                next.extend_from_slice(b"%5B");
                            }
                        }
                    }
                    self.hash(value, Some(&next), None);
                }
                Value::Null => {}
                _ => self.scalar(&key, value, prefix, numeric_prefix),
            }
        }
    }
}

/// PHP `http_build_query($data, $numeric_prefix, $arg_separator, $encoding_type)`
/// for data decoded from JSON (objects are PHP arrays; keys that are
/// canonical integers are integer keys, which get `numeric_prefix` at the
/// top level). Nested arrays become `a%5Bb%5D=...`; `null` values are
/// skipped, booleans are `1`/`0`, floats use `precision` 14.
/// `arg_separator` `None` is PHP's `arg_separator.output` default, `&`.
pub fn http_build_query(
    data: &Value,
    numeric_prefix: &[u8],
    arg_separator: Option<&[u8]>,
    encoding: QueryEncoding,
) -> Vec<u8> {
    let mut b = QueryBuilder {
        out: Vec::new(),
        separator: arg_separator.unwrap_or(b"&"),
        raw: encoding == QueryEncoding::Rfc3986,
    };
    b.hash(data, None, Some(numeric_prefix));
    b.out
}

