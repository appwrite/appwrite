/// The document type of the `ENT_HTML401`/`ENT_XML1`/`ENT_XHTML`/`ENT_HTML5` flags.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Doctype {
    /// `ENT_HTML401` (0), the default.
    #[default]
    Html401,
    /// `ENT_XML1` (16).
    Xml1,
    /// `ENT_XHTML` (32).
    Xhtml,
    /// `ENT_HTML5` (48).
    Html5,
}

/// The `$flags` of the HTML functions, decoded from PHP's bit mask.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct HtmlFlags {
    /// `ENT_HTML_QUOTE_SINGLE` (1): convert `'`.
    pub single_quotes: bool,
    /// `ENT_HTML_QUOTE_DOUBLE` (2, `ENT_COMPAT`): convert `"`.
    pub double_quotes: bool,
    /// `ENT_IGNORE` (4): drop invalid UTF-8 (wins over `substitute`).
    pub ignore: bool,
    /// `ENT_SUBSTITUTE` (8): replace invalid UTF-8 with U+FFFD. Without it
    /// (and without `ignore`) invalid UTF-8 makes the result empty.
    pub substitute: bool,
    /// `ENT_DISALLOWED` (128): replace code points the doctype disallows.
    pub disallowed: bool,
    pub doctype: Doctype,
}

impl HtmlFlags {
    /// PHP's default, `ENT_QUOTES | ENT_SUBSTITUTE | ENT_HTML401`.
    pub const DEFAULT: Self = Self::from_php(3 | 8);

    /// The flags of PHP's integer `$flags` (other bits are ignored, as in PHP).
    pub const fn from_php(flags: i64) -> Self {
        HtmlFlags {
            single_quotes: flags & 1 != 0,
            double_quotes: flags & 2 != 0,
            ignore: flags & 4 != 0,
            substitute: flags & 8 != 0,
            disallowed: flags & 128 != 0,
            doctype: match flags & 48 {
                0 => Doctype::Html401,
                16 => Doctype::Xml1,
                32 => Doctype::Xhtml,
                _ => Doctype::Html5,
            },
        }
    }
}

impl Default for HtmlFlags {
    fn default() -> Self {
        Self::DEFAULT
    }
}

/// `get_next_char` for UTF-8: a code point, or how many bytes an invalid
/// sequence spans (PHP's "strategy 2" of UTR #36).
fn next_utf8(s: &[u8], pos: usize) -> Result<(u32, usize), usize> {
    let avail = s.len() - pos;
    let c = s[pos];
    let lead = |b: u8| b < 0x80 || (0xC2..=0xF4).contains(&b);
    let trail = |b: u8| (0x80..=0xBF).contains(&b);
    if c < 0x80 {
        return Ok((c as u32, 1));
    }
    if c < 0xC2 {
        return Err(1);
    }
    if c < 0xE0 {
        if avail < 2 {
            return Err(1);
        }
        if !trail(s[pos + 1]) {
            return Err(if lead(s[pos + 1]) { 1 } else { 2 });
        }
        return Ok((((c as u32 & 0x1F) << 6) | (s[pos + 1] as u32 & 0x3F), 2));
    }
    if c < 0xF0 {
        if avail < 3 || !trail(s[pos + 1]) || !trail(s[pos + 2]) {
            return Err(if avail < 2 || lead(s[pos + 1]) {
                1
            } else if avail < 3 || lead(s[pos + 2]) {
                2
            } else {
                3
            });
        }
        let cp = ((c as u32 & 0x0F) << 12) | ((s[pos + 1] as u32 & 0x3F) << 6) | (s[pos + 2] as u32 & 0x3F);
        if cp < 0x800 || (0xD800..=0xDFFF).contains(&cp) {
            return Err(3);
        }
        return Ok((cp, 3));
    }
    if c < 0xF5 {
        if avail < 4 || !trail(s[pos + 1]) || !trail(s[pos + 2]) || !trail(s[pos + 3]) {
            return Err(if avail < 2 || lead(s[pos + 1]) {
                1
            } else if avail < 3 || lead(s[pos + 2]) {
                2
            } else if avail < 4 || lead(s[pos + 3]) {
                3
            } else {
                4
            });
        }
        let cp = ((c as u32 & 0x07) << 18)
            | ((s[pos + 1] as u32 & 0x3F) << 12)
            | ((s[pos + 2] as u32 & 0x3F) << 6)
            | (s[pos + 3] as u32 & 0x3F);
        if !(0x10000..=0x10FFFF).contains(&cp) {
            return Err(4);
        }
        return Ok((cp, 4));
    }
    Err(1)
}

/// `unicode_cp_is_allowed`.
fn cp_allowed(cp: u32, doctype: Doctype) -> bool {
    match doctype {
        Doctype::Html401 => {
            (0x20..=0x7E).contains(&cp)
                || cp == 0x0A
                || cp == 0x09
                || cp == 0x0D
                || (0xA0..=0xD7FF).contains(&cp)
                || (0xE000..=0x10FFFF).contains(&cp)
        }
        Doctype::Html5 => {
            (0x20..=0x7E).contains(&cp)
                || ((0x09..=0x0D).contains(&cp) && cp != 0x0B)
                || (0xA0..=0xD7FF).contains(&cp)
                || ((0xE000..=0x10FFFF).contains(&cp) && (cp & 0xFFFF) < 0xFFFE && !(0xFDD0..=0xFDEF).contains(&cp))
        }
        Doctype::Xhtml | Doctype::Xml1 => {
            (0x20..=0xD7FF).contains(&cp)
                || cp == 0x0A
                || cp == 0x09
                || cp == 0x0D
                || ((0xE000..=0x10FFFF).contains(&cp) && cp != 0xFFFE && cp != 0xFFFF)
        }
    }
}

/// `numeric_entity_is_allowed`.
fn numeric_allowed(cp: u32, doctype: Doctype) -> bool {
    match doctype {
        Doctype::Html401 => cp <= 0x10FFFF,
        Doctype::Html5 => {
            (0x20..=0x7E).contains(&cp)
                || ((0x09..=0x0C).contains(&cp) && cp != 0x0B)
                || ((0xA0..=0x10FFFF).contains(&cp) && (cp & 0xFFFF) < 0xFFFE && !(0xFDD0..=0xFDEF).contains(&cp))
        }
        Doctype::Xhtml | Doctype::Xml1 => cp_allowed(cp, doctype),
    }
}

/// `process_numeric_entity` from `pos` (just after `&#`): the code point and
/// the position of the closing `;`. Digits are read like C `strtol` (which
/// also accepts a `0x` prefix in hexadecimal entities).
fn numeric_entity(s: &[u8], pos: usize) -> Option<(u32, usize)> {
    let at = |k: usize| s.get(k).copied().unwrap_or(0);
    let mut p = pos;
    let hex = at(p) == b'x' || at(p) == b'X';
    if hex {
        p += 1;
    }
    if (hex && !at(p).is_ascii_hexdigit()) || (!hex && !at(p).is_ascii_digit()) {
        return None;
    }
    let base: u64 = if hex { 16 } else { 10 };
    if hex && at(p) == b'0' && at(p + 1) | 32 == b'x' {
        if at(p + 2).is_ascii_hexdigit() {
            p += 2;
        } else {
            // strtol stops after the "0"
            return if at(p + 1) == b';' { Some((0, p + 1)) } else { None };
        }
    }
    let mut value: u64 = 0;
    while at(p).is_ascii_hexdigit() && (hex || at(p).is_ascii_digit()) {
        value = value.saturating_mul(base).saturating_add(hex_value(at(p)) as u64);
        p += 1;
    }
    if at(p) != b';' || value > 0x10FFFF {
        return None;
    }
    Some((value as u32, p))
}

/// `process_named_entity_html` from `pos` (just after `&`): the name's end
/// (the `;`), for `[A-Za-z0-9]+;`.
fn named_entity(s: &[u8], pos: usize) -> Option<usize> {
    let mut p = pos;
    while p < s.len() && s[p].is_ascii_alphanumeric() {
        p += 1;
    }
    if p == pos || s.get(p) != Some(&b';') {
        return None;
    }
    Some(p)
}

fn decode_table(doctype: Doctype) -> &'static [(&'static str, u32, u32)] {
    match doctype {
        Doctype::Html5 => html_tables::HTML5_DECODE,
        _ => html_tables::HTML401_DECODE,
    }
}

/// A named entity for decoding (`resolve_named_entity_html`): `all` selects
/// the doctype's full table, else (and for XML 1.0) the basic entities.
fn resolve_named(name: &[u8], all: bool, doctype: Doctype) -> Option<(u32, u32)> {
    let basic = |apos: bool| -> Option<(u32, u32)> {
        Some(match name {
            b"quot" => (0x22, 0),
            b"amp" => (0x26, 0),
            b"lt" => (0x3C, 0),
            b"gt" => (0x3E, 0),
            b"apos" if apos => (0x27, 0),
            b"#039" if !apos => (0x27, 0),
            _ => return None,
        })
    };
    if !all {
        return basic(doctype != Doctype::Html401);
    }
    match doctype {
        Doctype::Xml1 => basic(true),
        _ => {
            let table = decode_table(doctype);
            table.binary_search_by(|(n, _, _)| n.as_bytes().cmp(name)).ok().map(|i| (table[i].1, table[i].2))
        }
    }
}

/// The basic entity of a character (`stage3_table_be_*`): XHTML, XML 1.0
/// and HTML5 use `apos`, HTML 4.01 `#039`.
fn basic_entity(c: u32, doctype: Doctype) -> Option<&'static str> {
    match c {
        0x22 => Some("quot"),
        0x26 => Some("amp"),
        0x27 => Some(if doctype == Doctype::Html401 { "#039" } else { "apos" }),
        0x3C => Some("lt"),
        0x3E => Some("gt"),
        _ => None,
    }
}

fn escape(s: &[u8], flags: HtmlFlags, double_encode: bool, all: bool) -> Vec<u8> {
    let doctype = flags.doctype;
    let all = all && doctype != Doctype::Xml1;
    let mut out = Vec::with_capacity(s.len() + s.len() / 4 + 16);
    let mut cursor = 0;
    while cursor < s.len() {
        let before = cursor;
        let (c, len) = match next_utf8(s, cursor) {
            Ok(v) => v,
            Err(advance) => {
                cursor += advance;
                if flags.ignore {
                    continue;
                } else if flags.substitute {
                    out.extend_from_slice("\u{FFFD}".as_bytes());
                    continue;
                }
                return Vec::new();
            }
        };
        cursor += len;
        if c != u32::from(b'&') {
            if (c == 0x27 && !flags.single_quotes) || (c == 0x22 && !flags.double_quotes) {
                out.extend_from_slice(&s[before..cursor]);
                continue;
            }
            let entity: Option<&str> = if all {
                if doctype == Doctype::Html5 {
                    let pair = html_tables::HTML5_ENCODE_PAIRS.iter().any(|&(a, _, _)| a == c);
                    let mut found = None;
                    if pair
                        && cursor < s.len()
                        && let Ok((next, next_len)) = next_utf8(s, cursor)
                        && let Some(&(_, _, name)) =
                            html_tables::HTML5_ENCODE_PAIRS.iter().find(|&&(a, b, _)| a == c && b == next)
                    {
                        found = Some(name);
                        cursor += next_len;
                    }
                    found.or_else(|| lookup_encode(html_tables::HTML5_ENCODE, c))
                } else {
                    lookup_encode(html_tables::HTML401_ENCODE, c)
                }
            } else {
                basic_entity(c, doctype)
            };
            match entity {
                Some(name) => {
                    out.push(b'&');
                    out.extend_from_slice(name.as_bytes());
                    out.push(b';');
                }
                None => {
                    if flags.disallowed && !cp_allowed(c, doctype) {
                        out.extend_from_slice("\u{FFFD}".as_bytes());
                    } else {
                        out.extend_from_slice(&s[before..cursor]);
                    }
                }
            }
            continue;
        }
        // '&'
        if !double_encode {
            let valid_end = if s.get(cursor) == Some(&b'#') {
                numeric_entity(s, cursor + 1)
                    .filter(|&(cp, _)| !flags.disallowed || numeric_allowed(cp, doctype))
                    .map(|(_, e)| e)
            } else {
                named_entity(s, cursor).filter(|&end| {
                    let name = &s[cursor..end];
                    resolve_named(name, true, doctype).is_some() || (doctype == Doctype::Xhtml && name == b"apos")
                })
            };
            if let Some(end) = valid_end {
                out.push(b'&');
                out.extend_from_slice(&s[cursor..end]);
                out.push(b';');
                cursor = end + 1;
                continue;
            }
        }
        out.extend_from_slice(b"&amp;");
    }
    out
}

fn lookup_encode(table: &[(u32, &'static str)], c: u32) -> Option<&'static str> {
    table.binary_search_by_key(&c, |&(k, _)| k).ok().map(|i| table[i].1)
}

/// PHP `htmlspecialchars($string, $flags, 'UTF-8', $double_encode)`:
/// escapes `& < >` and the quotes `flags` selects (`'` as `&#039;` in HTML
/// 4.01, `&apos;` otherwise). With `double_encode` false, existing valid
/// entities are kept. Invalid UTF-8 follows `ENT_IGNORE`/`ENT_SUBSTITUTE`,
/// else the result is empty.
pub fn htmlspecialchars(s: &[u8], flags: HtmlFlags, double_encode: bool) -> Vec<u8> {
    escape(s, flags, double_encode, false)
}

/// PHP `htmlentities($string, $flags, 'UTF-8', $double_encode)`: like
/// [`htmlspecialchars`] but every character with a named entity in the
/// doctype's table is converted (HTML 4.01 and XHTML: 253 entities, HTML5:
/// 1511 including two-character ones such as `fj`; XML 1.0: the basic ones).
pub fn htmlentities(s: &[u8], flags: HtmlFlags, double_encode: bool) -> Vec<u8> {
    escape(s, flags, double_encode, true)
}

fn write_utf8(out: &mut Vec<u8>, cp: u32) {
    if let Some(c) = char::from_u32(cp) {
        let mut buf = [0u8; 4];
        out.extend_from_slice(c.encode_utf8(&mut buf).as_bytes());
    }
}

const LONGEST_ENTITY_LENGTH: usize = 31;

fn unescape(s: &[u8], flags: HtmlFlags, all: bool) -> Cow<'_, [u8]> {
    if !s.contains(&b'&') {
        return Cow::Borrowed(s);
    }
    let doctype = flags.doctype;
    let mut out = Vec::with_capacity(s.len());
    let mut cur = 0;
    while cur < s.len() {
        let Some(amp) = s[cur..].iter().position(|&c| c == b'&') else {
            out.extend_from_slice(&s[cur..]);
            break;
        };
        out.extend_from_slice(&s[cur..cur + amp]);
        cur += amp;
        if s.len() - cur < 4 {
            out.extend_from_slice(&s[cur..]);
            break;
        }
        // (code, code2, position of ';'), or None for an invalid entity.
        let parsed: Option<(u32, u32, usize)> = if s[cur + 1] == b'#' {
            numeric_entity(s, cur + 2).and_then(|(code, end)| {
                let basic_ok = code <= 63 && basic_entity(code, Doctype::Xhtml).is_some();
                if (!all && !basic_ok) || !cp_allowed(code, doctype) || (doctype == Doctype::Html5 && code == 0x0D) {
                    None
                } else {
                    Some((code, 0, end))
                }
            })
        } else {
            let name_start = cur + 1;
            let window = (LONGEST_ENTITY_LENGTH + 1).min(s.len() - name_start);
            s[name_start..name_start + window].iter().position(|&c| c == b';').and_then(|n| {
                if n == 0 {
                    return None;
                }
                let name = &s[name_start..name_start + n];
                match resolve_named(name, all, doctype) {
                    Some((a, b)) => Some((a, b, name_start + n)),
                    None if doctype == Doctype::Xhtml && name == b"apos" => Some((0x27, 0, name_start + n)),
                    None => None,
                }
            })
        };
        let Some((code, code2, end)) = parsed else {
            out.push(b'&');
            cur += 1;
            continue;
        };
        let quote_off = (code == 0x27 && !flags.single_quotes) || (code == 0x22 && !flags.double_quotes);
        if quote_off || (!all && (code > 0xFF || code2 != 0)) {
            // Invalid once parsed: copy up to the ';', which is then copied as text.
            out.extend_from_slice(&s[cur..end]);
            cur = end;
            continue;
        }
        write_utf8(&mut out, code);
        if code2 != 0 {
            write_utf8(&mut out, code2);
        }
        cur = end + 1;
    }
    Cow::Owned(out)
}

/// PHP `htmlspecialchars_decode($string, $flags)`: decodes `&amp; &lt; &gt;`
/// and the quotes `flags` selects (`&quot;`, `&#039;`/`&apos;` by doctype),
/// named or numeric.
pub fn htmlspecialchars_decode(s: &[u8], flags: HtmlFlags) -> Cow<'_, [u8]> {
    unescape(s, flags, false)
}

/// PHP `html_entity_decode($string, $flags, 'UTF-8')`: decodes every named
/// entity of the doctype's table and numeric entities of code points the
/// doctype allows, to UTF-8.
pub fn html_entity_decode(s: &[u8], flags: HtmlFlags) -> Cow<'_, [u8]> {
    unescape(s, flags, true)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn url_like_php() {
        assert_eq!(urlencode(b"a b~c&"), "a+b%7Ec%26");
        assert_eq!(rawurlencode(b"a b~c&"), "a%20b~c%26");
        assert_eq!(urldecode(b"a+b%2"), b"a b%2");
    }

    #[test]
    fn query_like_php() {
        let data = json!({"a": 1, "b": [1, {"c": "x y"}], "0": true, "n": null});
        assert_eq!(
            http_build_query(&data, b"p", None, QueryEncoding::Rfc1738),
            b"a=1&b%5B0%5D=1&b%5B1%5D%5Bc%5D=x+y&p0=1"
        );
    }

    #[test]
    fn base64_like_php() {
        assert_eq!(base64_encode(b"ab"), "YWI=");
        assert_eq!(base64_decode(b"YW I=", true).unwrap(), b"ab");
        assert_eq!(base64_decode(b"YWI=x", true), None);
        assert_eq!(base64_decode(b"Y!WI", false).unwrap(), b"ab");
    }

    #[test]
    fn html_like_php() {
        let f = HtmlFlags::DEFAULT;
        assert_eq!(
            htmlspecialchars(b"<a href='x'>&amp;</a>", f, true),
            b"&lt;a href=&#039;x&#039;&gt;&amp;amp;&lt;/a&gt;"
        );
        assert_eq!(htmlspecialchars(b"&amp; &bogus;", f, false), b"&amp; &amp;bogus;");
        assert_eq!(htmlentities("café".as_bytes(), f, true), b"caf&eacute;");
        assert_eq!(html_entity_decode(b"&eacute;&#x41;&apos;", f).as_ref(), "éA&apos;".as_bytes());
        assert_eq!(htmlspecialchars(b"a\xFFb", HtmlFlags::from_php(3), true), b"");
    }
}
