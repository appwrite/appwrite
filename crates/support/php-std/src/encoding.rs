const HEX_UPPER: &[u8; 16] = b"0123456789ABCDEF";
const HEX_LOWER: &[u8; 16] = b"0123456789abcdef";

// ---------------------------------------------------------------------------
// URL encoding
// ---------------------------------------------------------------------------

fn url_encode_into(out: &mut Vec<u8>, s: &[u8], raw: bool) {
    for &c in s {
        if !raw && c == b' ' {
            out.push(b'+');
        } else if c.is_ascii_alphanumeric() || c == b'-' || c == b'.' || c == b'_' || (raw && c == b'~') {
            out.push(c);
        } else {
            out.extend_from_slice(&[b'%', HEX_UPPER[(c >> 4) as usize], HEX_UPPER[(c & 15) as usize]]);
        }
    }
}

/// PHP `urlencode`: `application/x-www-form-urlencoded` (RFC 1738):
/// alphanumerics and `-_.` are kept, a space is `+`, every other byte
/// (including `~`) is `%XX`.
pub fn urlencode(s: &[u8]) -> String {
    let mut out = Vec::with_capacity(s.len() * 3);
    url_encode_into(&mut out, s, false);
    String::from_utf8(out).unwrap_or_default()
}

/// PHP `rawurlencode` (RFC 3986): alphanumerics and `-_.~` are kept, every
/// other byte is `%XX`.
pub fn rawurlencode(s: &[u8]) -> String {
    let mut out = Vec::with_capacity(s.len() * 3);
    url_encode_into(&mut out, s, true);
    String::from_utf8(out).unwrap_or_default()
}

fn url_decode(s: &[u8], plus: bool) -> Vec<u8> {
    let mut out = Vec::with_capacity(s.len());
    let mut i = 0;
    while i < s.len() {
        let c = s[i];
        if plus && c == b'+' {
            out.push(b' ');
        } else if c == b'%' && i + 2 < s.len() && s[i + 1].is_ascii_hexdigit() && s[i + 2].is_ascii_hexdigit() {
            out.push(hex_value(s[i + 1]) * 16 + hex_value(s[i + 2]));
            i += 2;
        } else {
            out.push(c);
        }
        i += 1;
    }
    out
}

/// PHP `urldecode`: `+` is a space and `%XX` a byte; a `%` not followed by
/// two hex digits is kept.
pub fn urldecode(s: &[u8]) -> Vec<u8> {
    url_decode(s, true)
}

/// PHP `rawurldecode`: `%XX` is a byte (`+` stays `+`).
pub fn rawurldecode(s: &[u8]) -> Vec<u8> {
    url_decode(s, false)
}

