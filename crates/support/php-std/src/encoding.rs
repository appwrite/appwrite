/// PHP `addslashes`: backslash before `'`, `"` and `\`, and NUL as `\0`.
pub fn addslashes(s: &[u8]) -> Cow<'_, [u8]> {
    if !s.iter().any(|&c| matches!(c, 0 | b'\'' | b'"' | b'\\')) {
        return Cow::Borrowed(s);
    }
    let mut out = Vec::with_capacity(s.len() + 8);
    for &c in s {
        match c {
            0 => out.extend_from_slice(b"\\0"),
            b'\'' | b'"' | b'\\' => out.extend_from_slice(&[b'\\', c]),
            _ => out.push(c),
        }
    }
    Cow::Owned(out)
}

/// PHP `stripslashes`: drops each backslash and keeps the byte after it
/// (`\0` is NUL); a trailing backslash is dropped.
pub fn stripslashes(s: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(s.len());
    let mut i = 0;
    while i < s.len() {
        if s[i] == b'\\' {
            i += 1;
            if i < s.len() {
                out.push(if s[i] == b'0' { 0 } else { s[i] });
                i += 1;
            }
        } else {
            out.push(s[i]);
            i += 1;
        }
    }
    out
}

/// PHP `quoted_printable_encode` (RFC 2045, lines of at most 76 bytes with
/// PHP's look-ahead for multi-byte UTF-8 lead bytes).
pub fn quoted_printable_encode(s: &[u8]) -> Vec<u8> {
    const MAXL: u64 = 75;
    let mut out = Vec::with_capacity(s.len() * 3);
    let mut lp: u64 = 0;
    let mut i = 0;
    let at = |k: usize| s.get(k).copied().unwrap_or(0);
    while i < s.len() {
        let c = s[i];
        i += 1;
        let remaining = s.len() - i;
        if c == b'\r' && at(i) == b'\n' && remaining > 0 {
            out.extend_from_slice(b"\r\n");
            i += 1;
            lp = 0;
        } else if c < 32 || c == 0x7f || c & 0x80 != 0 || c == b'=' || (c == b' ' && at(i) == b'\r') {
            lp += 3;
            if (lp > MAXL && c <= 0x7f)
                || (c > 0x7f && c <= 0xdf && lp + 3 > MAXL)
                || (c > 0xdf && c <= 0xef && lp + 6 > MAXL)
                || (c > 0xef && c <= 0xf4 && lp + 9 > MAXL)
            {
                out.extend_from_slice(b"=\r\n");
                lp = 3;
            }
            out.extend_from_slice(&[b'=', HEX_UPPER[(c >> 4) as usize], HEX_UPPER[(c & 15) as usize]]);
        } else {
            lp += 1;
            if lp > MAXL {
                out.extend_from_slice(b"=\r\n");
                lp = 1;
            }
            out.push(c);
        }
    }
    out
}

/// PHP `quoted_printable_decode`: `=XX` is a byte, `=` before (spaces and)
/// a line break or the end is a soft break. Stops at a NUL byte, as PHP does.
pub fn quoted_printable_decode(s: &[u8]) -> Vec<u8> {
    let at = |k: usize| s.get(k).copied().unwrap_or(0);
    let mut out = Vec::with_capacity(s.len());
    let mut i = 0;
    while at(i) != 0 {
        if at(i) == b'=' {
            if at(i + 1) != 0 && at(i + 2) != 0 && at(i + 1).is_ascii_hexdigit() && at(i + 2).is_ascii_hexdigit() {
                out.push(hex_value(at(i + 1)) * 16 + hex_value(at(i + 2)));
                i += 3;
            } else {
                let mut k = 1;
                while at(i + k) != 0 && (at(i + k) == b' ' || at(i + k) == b'\t') {
                    k += 1;
                }
                if at(i + k) == 0 {
                    i += k;
                } else if at(i + k) == b'\r' && at(i + k + 1) == b'\n' {
                    i += k + 2;
                } else if at(i + k) == b'\r' || at(i + k) == b'\n' {
                    i += k + 1;
                } else {
                    out.push(at(i));
                    i += 1;
                }
            }
        } else {
            out.push(at(i));
            i += 1;
        }
    }
    out
}

