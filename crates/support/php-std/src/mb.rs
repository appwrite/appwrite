fn lookup(table: &[(u32, u32)], code: u32) -> Option<u32> {
    table.binary_search_by_key(&code, |&(k, _)| k).ok().map(|i| table[i].1)
}

fn in_ranges(ranges: &[(u32, u32)], code: u32) -> bool {
    match ranges.binary_search_by(|&(lo, _)| lo.cmp(&code)) {
        Ok(_) => true,
        Err(0) => false,
        Err(i) => code <= ranges[i - 1].1,
    }
}

fn is_cased(w: u32) -> bool {
    in_ranges(unicode::CASED, w)
}

fn is_case_ignorable(w: u32) -> bool {
    in_ranges(unicode::CASE_IGNORABLE, w)
}

fn tolower_raw(code: u32) -> u32 {
    if code < 0xC0 {
        if (0x41..=0x5A).contains(&code) { code + 0x20 } else { code }
    } else {
        lookup(unicode::LOWER, code).unwrap_or(code)
    }
}

/// Writes a full mapping (`emit_special_casing_sequence`) or a code point.
fn emit(raw: u32, out: &mut [u32; 192], p: &mut usize) {
    if raw > 0xFFFFFF {
        let len = (raw >> 24) as usize;
        let at = (raw & 0xFFFFFF) as usize;
        for &w in &unicode::EXTRA[at + 1..=at + len] {
            out[*p] = w;
            *p += 1;
        }
    } else {
        out[*p] = raw;
        *p += 1;
    }
}

/// Whether the rest of the input, after the current chunk, continues with a
/// cased letter (skipping case-ignorable characters).
fn scan_ahead_for_cased(s: &[u8], mut pos: usize) -> bool {
    while pos < s.len() {
        let w = decode_one(s, &mut pos);
        if is_cased(w) {
            return true;
        }
        if !is_case_ignorable(w) {
            return false;
        }
    }
    false
}

/// `scan_back_for_cased_letter`: looks through what is left of the previous
/// chunk's converted output (`converted[begin..end]`, backwards).
fn scan_back_for_cased(converted: &[u32; 192], begin: usize, end: Option<usize>) -> bool {
    let Some(mut e) = end else { return false };
    while e > begin {
        e -= 1;
        let w = converted[e];
        if is_cased(w) {
            return true;
        }
        if !is_case_ignorable(w) {
            return false;
        }
    }
    false
}

/// Whether the capital sigma at `i` of the chunk ends a word (PHP's final
/// sigma rule, with its chunk-limited look-behind).
fn is_final_sigma(
    wbuf: &[u32],
    i: usize,
    s: &[u8],
    pos: usize,
    converted: &[u32; 192],
    p: usize,
    converted_end: Option<usize>,
) -> bool {
    let mut j = i as isize - 1;
    while j >= 0 && is_case_ignorable(wbuf[j as usize]) {
        j -= 1;
    }
    let before = if j >= 0 { is_cased(wbuf[j as usize]) } else { scan_back_for_cased(converted, p, converted_end) };
    if !before {
        return false;
    }
    let mut j = i + 1;
    while j < wbuf.len() && is_case_ignorable(wbuf[j]) {
        j += 1;
    }
    if j >= wbuf.len() { !scan_ahead_for_cased(s, pos) } else { !is_cased(wbuf[j]) }
}

/// `php_unicode_convert_case` (`MB_CASE_LOWER`) for UTF-8 in and out, in
/// chunks of 64 code points like PHP (the final-sigma look-behind depends on
/// them).
fn convert_case(s: &[u8], bad: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(s.len() + 1);
    let mut converted = [0u32; 192];
    let mut converted_end: Option<usize> = None;
    let mut pos = 0;
    let mut wbuf = [0u32; 64];
    while pos < s.len() {
        let mut n = 0;
        while pos < s.len() && n < 64 {
            wbuf[n] = decode_one(s, &mut pos);
            n += 1;
        }
        let w_in = &wbuf[..n];
        let mut p = 0;
        for (i, &w) in w_in.iter().enumerate() {
            if w > 0xFFFFFF {
                converted[p] = w;
                p += 1;
                continue;
            }
            if w == 0x3A3 && is_final_sigma(w_in, i, s, pos, &converted, p, converted_end) {
                converted[p] = 0x3C2;
                p += 1;
            } else {
                emit(tolower_raw(w), &mut converted, &mut p);
            }
        }
        converted_end = Some(p);
        for &w in &converted[..p] {
            encode(&mut out, w, bad);
        }
    }
    out
}

/// PHP `mb_strtolower($string)`: full lower case with the final sigma rule
/// (`MB_CASE_LOWER`).
pub fn mb_strtolower(s: &[u8]) -> Vec<u8> {
    map_case(s).unwrap_or_else(|| convert_case(s, SUBSTITUTE))
}

/// [`convert_case`] where each code point maps on its own: ASCII runs are
/// converted in bulk, without the chunking. `None` for a capital sigma (the
/// final sigma rule looks at its neighbours, within PHP's chunks).
fn map_case(s: &[u8]) -> Option<Vec<u8>> {
    // The raw mappings of the first code points (Latin, Greek, Cyrillic,
    // Armenian, Hebrew), looked up directly instead of searched.
    const DIRECT: usize = 0x600;
    static TABLE: OnceLock<Vec<u32>> = OnceLock::new();
    let direct = TABLE.get_or_init(|| (0..DIRECT as u32).map(tolower_raw).collect());
    let mut out = Vec::with_capacity(s.len() + s.len() / 4 + 1);
    let mut pos = 0;
    while pos < s.len() {
        let run = s[pos..].iter().position(|&c| c >= 0x80).map_or(s.len(), |n| pos + n);
        out.extend(s[pos..run].iter().map(u8::to_ascii_lowercase));
        pos = run;
        if pos == s.len() {
            break;
        }
        let w = decode_one(s, &mut pos);
        if w > 0xFFFFFF {
            encode(&mut out, w, SUBSTITUTE);
            continue;
        }
        if w == 0x3A3 {
            return None;
        }
        let raw = direct.get(w as usize).copied().unwrap_or_else(|| tolower_raw(w));
        if raw > 0xFFFFFF {
            let len = (raw >> 24) as usize;
            let at = (raw & 0xFFFFFF) as usize;
            for &w in &unicode::EXTRA[at + 1..=at + len] {
                encode(&mut out, w, SUBSTITUTE);
            }
        } else {
            encode(&mut out, raw, SUBSTITUTE);
        }
    }
    Some(out)
}

