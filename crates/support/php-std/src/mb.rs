mod width;

use std::borrow::Cow;
use std::sync::OnceLock;

use crate::string::Error;

/// mbstring's error marker for an invalid byte sequence (`MBFL_BAD_INPUT`).
const BAD: u32 = u32::MAX;

/// `mblen_table_utf8`: the length a lead byte announces (1 for anything else).
fn utf8_len(b: u8) -> usize {
    match b {
        0xC2..=0xDF => 2,
        0xE0..=0xEF => 3,
        0xF0..=0xF4 => 4,
        _ => 1,
    }
}

fn is_continuation(b: u8) -> bool {
    (0x80..=0xBF).contains(&b)
}

/// `mb_utf8_to_wchar` for one code point: decodes at `*pos` and advances;
/// an invalid sequence yields [`BAD`] and consumes what PHP consumes.
fn decode_one(s: &[u8], pos: &mut usize) -> u32 {
    let e = s.len();
    let mut p = *pos;
    let c = s[p];
    p += 1;
    let w = if c < 0x80 {
        c as u32
    } else if c < 0xC2 {
        BAD
    } else if c <= 0xDF {
        if p < e {
            let c2 = s[p];
            p += 1;
            if c2 & 0xC0 != 0x80 {
                p -= 1;
                BAD
            } else {
                ((c as u32 & 0x1F) << 6) | (c2 as u32 & 0x3F)
            }
        } else {
            BAD
        }
    } else if c <= 0xEF {
        if e - p >= 2 {
            let (c2, c3) = (s[p], s[p + 1]);
            p += 2;
            if c2 & 0xC0 != 0x80 || (c == 0xE0 && c2 < 0xA0) || (c == 0xED && c2 >= 0xA0) {
                p -= 2;
                BAD
            } else if c3 & 0xC0 != 0x80 {
                p -= 1;
                BAD
            } else {
                ((c as u32 & 0xF) << 12) | ((c2 as u32 & 0x3F) << 6) | (c3 as u32 & 0x3F)
            }
        } else {
            if p < e && (c != 0xE0 || s[p] >= 0xA0) && (c != 0xED || s[p] < 0xA0) && s[p] & 0xC0 == 0x80 {
                p += 1;
                if p < e && s[p] & 0xC0 == 0x80 {
                    p += 1;
                }
            }
            BAD
        }
    } else if c <= 0xF4 {
        if e - p >= 3 {
            let (c2, c3, c4) = (s[p], s[p + 1], s[p + 2]);
            p += 3;
            if c2 & 0xC0 != 0x80 || (c == 0xF0 && c2 < 0x90) || (c == 0xF4 && c2 >= 0x90) {
                p -= 3;
                BAD
            } else if c3 & 0xC0 != 0x80 {
                p -= 2;
                BAD
            } else if c4 & 0xC0 != 0x80 {
                p -= 1;
                BAD
            } else {
                ((c as u32 & 0x7) << 18) | ((c2 as u32 & 0x3F) << 12) | ((c3 as u32 & 0x3F) << 6) | (c4 as u32 & 0x3F)
            }
        } else {
            if p < e {
                let c2 = s[p];
                if (c == 0xF0 && c2 >= 0x90) || (c == 0xF4 && c2 < 0x90) || (0xF1..=0xF3).contains(&c) {
                    while p < e && s[p] & 0xC0 == 0x80 {
                        p += 1;
                    }
                }
            }
            BAD
        }
    } else {
        BAD
    };
    *pos = p;
    w
}

/// The code points (and error markers) of `s`, as mbstring decodes UTF-8.
fn decode(s: &[u8]) -> impl Iterator<Item = u32> + '_ {
    let mut pos = 0;
    std::iter::from_fn(move || if pos < s.len() { Some(decode_one(s, &mut pos)) } else { None })
}

/// `mb_wchar_to_utf8`: appends `w`, or `bad` for an error marker or a value
/// beyond U+10FFFF. (PHP 8.5.10 encodes surrogates as they are.)
fn encode(out: &mut Vec<u8>, w: u32, bad: &[u8]) {
    if w < 0x80 {
        out.push(w as u8);
    } else if w < 0x800 {
        out.extend_from_slice(&[0xC0 | (w >> 6) as u8, 0x80 | (w & 0x3F) as u8]);
    } else if w < 0x10000 {
        out.extend_from_slice(&[0xE0 | (w >> 12) as u8, 0x80 | ((w >> 6) & 0x3F) as u8, 0x80 | (w & 0x3F) as u8]);
    } else if w < 0x110000 {
        out.extend_from_slice(&[
            0xF0 | (w >> 18) as u8,
            0x80 | ((w >> 12) & 0x3F) as u8,
            0x80 | ((w >> 6) & 0x3F) as u8,
            0x80 | (w & 0x3F) as u8,
        ]);
    } else {
        out.extend_from_slice(bad);
    }
}

/// What PHP writes for an invalid sequence when it re-encodes text.
const SUBSTITUTE: &[u8] = b"?";

/// How many columns mbstring gives a character: 2 in its East Asian Width
/// table ([`width::WIDE`]), 1 otherwise (error markers included).
fn char_width(w: u32) -> usize {
    if !(0x1100..=0x3FFFD).contains(&w) {
        return 1;
    }
    let wide = width::WIDE
        .binary_search_by(|&(lo, hi)| {
            if hi < w {
                std::cmp::Ordering::Less
            } else if lo > w {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok();
    if wide { 2 } else { 1 }
}

/// PHP `mb_strimwidth($string, 0, $width)` (no trim marker): the longest
/// leading part of the string that fits in `width` columns. A string that
/// fits is returned as it is, except that invalid sequences become `?`, as
/// they do in a cut one.
///
/// ```
/// use php_std::mb::mb_strimwidth;
///
/// assert_eq!(mb_strimwidth("你好".as_bytes(), 3).as_ref(), "你".as_bytes());
/// assert_eq!(mb_strimwidth(b"abc", 5).as_ref(), b"abc");
/// assert_eq!(mb_strimwidth(b"abc\xff\xfedef", 5).as_ref(), b"abc??");
/// ```
pub fn mb_strimwidth(s: &[u8], width: usize) -> Cow<'_, [u8]> {
    let mut remaining = width;
    let mut out = Vec::new();
    let mut bad = false;
    for w in decode(s) {
        let columns = char_width(w);
        if remaining < columns {
            return Cow::Owned(out);
        }
        remaining -= columns;
        bad |= w == BAD;
        encode(&mut out, w, SUBSTITUTE);
    }
    if bad { Cow::Owned(out) } else { Cow::Borrowed(s) }
}
/// An encoding `mb_strlen` accepts.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Encoding {
    /// `UTF-8` (PHP's default internal encoding).
    #[default]
    Utf8,
    /// `8bit` (alias `binary`): one character per byte.
    EightBit,
}

impl Encoding {
    /// The encoding for one of PHP's names (case-insensitive): `UTF-8`,
    /// `UTF8`, `8bit`, `binary`. `None` for anything else (PHP's
    /// `ValueError` for an unknown encoding, or an encoding not ported).
    pub fn from_name(name: &str) -> Option<Self> {
        match name.to_ascii_lowercase().as_str() {
            "utf-8" | "utf8" => Some(Encoding::Utf8),
            "8bit" | "binary" => Some(Encoding::EightBit),
            _ => None,
        }
    }
}

/// PHP `mb_strlen($string)`: the number of characters; each invalid
/// sequence counts as one.
pub fn mb_strlen(s: &[u8]) -> usize {
    let mut pos = 0;
    let mut n = 0;
    while pos < s.len() {
        decode_one(s, &mut pos);
        n += 1;
    }
    n
}

/// PHP `mb_strlen($string, $encoding)` for the encodings in [`Encoding`].
pub fn mb_strlen_in(s: &[u8], encoding: Encoding) -> usize {
    match encoding {
        Encoding::Utf8 => mb_strlen(s),
        Encoding::EightBit => s.len(),
    }
}

/// PHP `mb_check_encoding($value, 'UTF-8')` on a string: strict UTF-8
/// (no overlong forms, surrogates or code points above U+10FFFF).
pub fn mb_check_encoding(s: &[u8]) -> bool {
    std::str::from_utf8(s).is_ok()
}

/// PHP `mb_scrub($string)` and `mb_convert_encoding($string, 'UTF-8')`
/// from UTF-8: each invalid sequence becomes `?`. Borrows valid input.
pub fn mb_scrub(s: &[u8]) -> Cow<'_, [u8]> {
    if mb_check_encoding(s) {
        return Cow::Borrowed(s);
    }
    let mut out = Vec::with_capacity(s.len());
    for w in decode(s) {
        encode(&mut out, w, SUBSTITUTE);
    }
    Cow::Owned(out)
}

/// `mb_get_substr`: `len` characters from character `from`, re-encoded
/// (invalid sequences become `?`).
fn get_substr(s: &[u8], from: usize, len: usize) -> Vec<u8> {
    if len == 0 || from >= s.len() {
        return Vec::new();
    }
    let mut out = Vec::new();
    for w in decode(s).skip(from).take(len) {
        encode(&mut out, w, SUBSTITUTE);
    }
    out
}

/// PHP `mb_substr($string, $start, $length)`: characters from `start`
/// (negative: from the end) for `length` characters (negative: stop that
/// many before the end; `None`: to the end). Re-encodes: invalid sequences
/// in the result become `?`. `PHP_INT_MIN` for either argument is PHP's
/// `ValueError`.
pub fn mb_substr(s: &[u8], start: i64, length: Option<i64>) -> Result<Vec<u8>, Error> {
    let range_error = |n: u32, name: &str| {
        Error::argument("mb_substr", n, name, &format!("must be between {} and {}", i64::MIN + 1, i64::MAX))
    };
    if start == i64::MIN {
        return Err(range_error(2, "start"));
    }
    if length == Some(i64::MIN) {
        return Err(range_error(3, "length"));
    }
    let mblen = if start < 0 || length.is_some_and(|l| l < 0) { mb_strlen(s) } else { 0 };
    let from = if start >= 0 {
        start as usize
    } else if start.unsigned_abs() < mblen as u64 {
        mblen - start.unsigned_abs() as usize
    } else {
        0
    };
    let len = match length {
        None => usize::MAX,
        Some(l) if l >= 0 => l as usize,
        Some(l) if from < mblen && l.unsigned_abs() < (mblen - from) as u64 => mblen - from - l.unsigned_abs() as usize,
        Some(_) => 0,
    };
    Ok(get_substr(s, from, len))
}

