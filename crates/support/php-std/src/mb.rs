/// `offset_to_pointer_utf8`: the byte position `offset` characters from the
/// start (or from the end, when negative), counting characters by lead bytes.
///
/// Deviation: PHP 8.5.10 can step past the end of a string that ends in a
/// truncated sequence and then reads out of bounds; this stops at the end
/// (as later PHP releases do).
fn offset_to_pointer(s: &[u8], offset: i64) -> Option<usize> {
    if offset < 0 {
        let mut pos = s.len();
        let mut offset = offset;
        while offset < 0 {
            if pos == 0 {
                return None;
            }
            pos -= 1;
            if !is_continuation(s[pos]) {
                offset += 1;
            }
        }
        Some(pos)
    } else {
        let mut pos = 0;
        let mut offset = offset;
        while offset > 0 {
            if pos >= s.len() {
                return None;
            }
            pos += utf8_len(s[pos]);
            offset -= 1;
        }
        Some(pos.min(s.len()))
    }
}

/// `pointer_to_offset_utf8`: characters (non-continuation bytes) before `pos`.
fn pointer_to_offset(s: &[u8], pos: usize) -> usize {
    s[..pos].iter().filter(|&&b| !is_continuation(b)).count()
}

/// `mb_find_strpos` on UTF-8 bytes.
fn find_strpos(function: &str, h: &[u8], n: &[u8], offset: i64, reverse: bool) -> Result<Option<usize>, Error> {
    let op = offset_to_pointer(h, offset)
        .ok_or_else(|| Error::argument(function, 3, "offset", "must be contained in argument #1 ($haystack)"))?;
    if h.len() < n.len() {
        return Ok(None);
    }
    let found = if !reverse {
        crate::string::find(&h[op..], n).map(|i| i + op)
    } else if offset >= 0 {
        crate::string::rfind(&h[op..], n).map(|i| i + op)
    } else {
        let needle_chars = pointer_to_offset(n, n.len());
        let end = offset_to_pointer(&h[op..], needle_chars as i64).map_or(h.len(), |e| op + e);
        crate::string::rfind(&h[..end], n)
    };
    Ok(found.map(|p| pointer_to_offset(h, p)))
}

/// PHP `mb_strpos($haystack, $needle, $offset)`: character position of the
/// first occurrence at or after `offset`. Matches bytes; positions count
/// lead bytes. `None` is PHP's `false`.
pub fn mb_strpos(haystack: &[u8], needle: &[u8], offset: i64) -> Result<Option<usize>, Error> {
    find_strpos("mb_strpos", haystack, needle, offset, false)
}

/// PHP `mb_strrpos($haystack, $needle, $offset)`: character position of the
/// last occurrence (a negative `offset` limits where the match may start).
pub fn mb_strrpos(haystack: &[u8], needle: &[u8], offset: i64) -> Result<Option<usize>, Error> {
    find_strpos("mb_strrpos", haystack, needle, offset, true)
}

/// Simple case folding for searching (invalid sequences become a byte that
/// cannot occur in UTF-8, as PHP's `BADUTF8` mode).
fn fold_for_search(s: &[u8]) -> Vec<u8> {
    convert_case(s, Case::FoldSimple, SEARCH_MARKER)
}

/// PHP `mb_stripos`: [`mb_strpos`] on simple-case-folded text.
pub fn mb_stripos(haystack: &[u8], needle: &[u8], offset: i64) -> Result<Option<usize>, Error> {
    find_strpos("mb_stripos", &fold_for_search(haystack), &fold_for_search(needle), offset, false)
}

/// PHP `mb_strripos`: [`mb_strrpos`] on simple-case-folded text.
pub fn mb_strripos(haystack: &[u8], needle: &[u8], offset: i64) -> Result<Option<usize>, Error> {
    find_strpos("mb_strripos", &fold_for_search(haystack), &fold_for_search(needle), offset, true)
}

fn strstr_variant(haystack: &[u8], found: Option<usize>, before_needle: bool) -> Option<Vec<u8>> {
    let n = found?;
    Some(if before_needle { get_substr(haystack, 0, n) } else { get_substr(haystack, n, usize::MAX) })
}

/// PHP `mb_strstr($haystack, $needle, $before_needle)`: the part from the
/// first occurrence (or before it), re-encoded. `None` is PHP's `false`.
pub fn mb_strstr(haystack: &[u8], needle: &[u8], before_needle: bool) -> Option<Vec<u8>> {
    let found = find_strpos("mb_strstr", haystack, needle, 0, false).ok().flatten();
    strstr_variant(haystack, found, before_needle)
}

/// PHP `mb_strrchr`: like [`mb_strstr`] from the last occurrence of `needle`.
pub fn mb_strrchr(haystack: &[u8], needle: &[u8], before_needle: bool) -> Option<Vec<u8>> {
    let found = find_strpos("mb_strrchr", haystack, needle, 0, true).ok().flatten();
    strstr_variant(haystack, found, before_needle)
}

/// PHP `mb_stristr`: [`mb_strstr`] matching simple-case-folded text.
pub fn mb_stristr(haystack: &[u8], needle: &[u8], before_needle: bool) -> Option<Vec<u8>> {
    let found =
        find_strpos("mb_stristr", &fold_for_search(haystack), &fold_for_search(needle), 0, false).ok().flatten();
    strstr_variant(haystack, found, before_needle)
}

/// PHP `mb_strrichr`: [`mb_strrchr`] matching simple-case-folded text.
pub fn mb_strrichr(haystack: &[u8], needle: &[u8], before_needle: bool) -> Option<Vec<u8>> {
    let found =
        find_strpos("mb_strrichr", &fold_for_search(haystack), &fold_for_search(needle), 0, true).ok().flatten();
    strstr_variant(haystack, found, before_needle)
}

/// Re-encodes with invalid sequences as the search marker byte.
fn for_search(s: &[u8]) -> Cow<'_, [u8]> {
    if mb_check_encoding(s) {
        return Cow::Borrowed(s);
    }
    let mut out = Vec::with_capacity(s.len());
    for w in decode(s) {
        encode(&mut out, w, SEARCH_MARKER);
    }
    Cow::Owned(out)
}

/// PHP `mb_substr_count($haystack, $needle)`: non-overlapping occurrences;
/// invalid sequences only match invalid sequences.
pub fn mb_substr_count(haystack: &[u8], needle: &[u8]) -> Result<usize, Error> {
    if needle.is_empty() {
        return Err(Error::argument("mb_substr_count", 2, "needle", "must not be empty"));
    }
    let (h, n) = (for_search(haystack), for_search(needle));
    let mut count = 0;
    let mut p = 0;
    while let Some(i) = crate::string::find(&h[p..], &n) {
        count += 1;
        p += i + n.len();
    }
    Ok(count)
}

