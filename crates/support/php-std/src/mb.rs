/// PHP `mb_str_pad($string, $length, $pad_string, $pad_type)`: pads to
/// `length` characters. Whole copies of `pad` are copied as bytes, the
/// partial copy is re-encoded.
pub fn mb_str_pad<'a>(s: &'a [u8], length: i64, pad: &[u8], pad_type: Pad) -> Result<Cow<'a, [u8]>, Error> {
    let input_len = mb_strlen(s);
    if length < 0 || (length as u64) <= input_len as u64 {
        return Ok(Cow::Borrowed(s));
    }
    let empty = || Error::argument("mb_str_pad", 3, "pad_string", "must not be empty");
    if pad.is_empty() {
        return Err(empty());
    }
    let pad_len = mb_strlen(pad);
    if pad_len == 0 {
        return Err(empty());
    }
    let (left, right) = pad_type.split(length as usize - input_len);
    let mut out = Vec::new();
    for _ in 0..left / pad_len {
        out.extend_from_slice(pad);
    }
    out.extend_from_slice(&get_substr(pad, 0, left % pad_len));
    out.extend_from_slice(s);
    for _ in 0..right / pad_len {
        out.extend_from_slice(pad);
    }
    out.extend_from_slice(&get_substr(pad, 0, right % pad_len));
    Ok(Cow::Owned(out))
}

/// `mb_trim`'s default characters: Unicode white space and NUL.
pub const MB_TRIM_CHARACTERS: &[u32] = &[
    0x20, 0x0C, 0x0A, 0x0D, 0x09, 0x0B, 0x00, 0xA0, 0x1680, 0x2000, 0x2001, 0x2002, 0x2003, 0x2004, 0x2005, 0x2006,
    0x2007, 0x2008, 0x2009, 0x200A, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000, 0x85, 0x180E,
];

fn trim_mode<'a>(s: &'a [u8], characters: Option<&[u8]>, left_mode: bool, right_mode: bool) -> Cow<'a, [u8]> {
    let set: Vec<u32> = match characters {
        None => MB_TRIM_CHARACTERS.to_vec(),
        Some([]) => return Cow::Borrowed(s),
        Some(c) => decode(c).collect(),
    };
    let (mut left, mut right, mut total) = (0usize, 0usize, 0usize);
    let mut ltrim = left_mode;
    for w in decode(s) {
        total += 1;
        if set.contains(&w) {
            if ltrim {
                left += 1;
            }
            if right_mode {
                right += 1;
            }
        } else {
            ltrim = false;
            if right_mode {
                right = 0;
            }
        }
    }
    if left == 0 && right == 0 {
        return Cow::Borrowed(s);
    }
    Cow::Owned(get_substr(s, left, total.saturating_sub(left + right)))
}

/// PHP `mb_trim($string, $characters)`: strips the characters of
/// `characters` (each code point; `None` for PHP's default, Unicode white
/// space) from both ends. When something is stripped, the rest is
/// re-encoded (invalid sequences become `?`); an invalid sequence in
/// `characters` strips invalid sequences.
pub fn mb_trim<'a>(s: &'a [u8], characters: Option<&[u8]>) -> Cow<'a, [u8]> {
    trim_mode(s, characters, true, true)
}

/// PHP `mb_ltrim`: [`mb_trim`] at the start only.
pub fn mb_ltrim<'a>(s: &'a [u8], characters: Option<&[u8]>) -> Cow<'a, [u8]> {
    trim_mode(s, characters, true, false)
}

/// PHP `mb_rtrim`: [`mb_trim`] at the end only.
pub fn mb_rtrim<'a>(s: &'a [u8], characters: Option<&[u8]>) -> Cow<'a, [u8]> {
    trim_mode(s, characters, false, true)
}

