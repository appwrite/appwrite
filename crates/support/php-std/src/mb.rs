/// `mb_convert_case()`'s `$mode` (`MB_CASE_*`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Case {
    /// `MB_CASE_UPPER` (0): full upper case (`ß` → `SS`).
    Upper,
    /// `MB_CASE_LOWER` (1): full lower case with the final sigma rule.
    Lower,
    /// `MB_CASE_TITLE` (2): title case per word, full mappings.
    Title,
    /// `MB_CASE_FOLD` (3): full case folding.
    Fold,
    /// `MB_CASE_UPPER_SIMPLE` (4).
    UpperSimple,
    /// `MB_CASE_LOWER_SIMPLE` (5).
    LowerSimple,
    /// `MB_CASE_TITLE_SIMPLE` (6).
    TitleSimple,
    /// `MB_CASE_FOLD_SIMPLE` (7).
    FoldSimple,
}

impl Case {
    /// The mode for PHP's `MB_CASE_*` value; `None` for anything else (PHP's
    /// `ValueError`).
    pub fn from_php(mode: i64) -> Option<Self> {
        Some(match mode {
            0 => Case::Upper,
            1 => Case::Lower,
            2 => Case::Title,
            3 => Case::Fold,
            4 => Case::UpperSimple,
            5 => Case::LowerSimple,
            6 => Case::TitleSimple,
            7 => Case::FoldSimple,
            _ => return None,
        })
    }
}

fn lookup(table: &[(u32, u32)], code: u32) -> Option<u32> {
    table.binary_search_by_key(&code, |&(k, _)| k).ok().map(|i| table[i].1)
}

fn in_ranges(ranges: &[(u32, u32)], code: u32) -> bool {
    match ranges.binary_search_by(|&(lo, _)| lo.cmp(&code)) {
        Ok(_) => true,
        Err(0) => false,
        Err(i) => code <= ranges[i - 1].1,
    }
}

fn is_cased(w: u32) -> bool {
    in_ranges(unicode::CASED, w)
}

fn is_case_ignorable(w: u32) -> bool {
    in_ranges(unicode::CASE_IGNORABLE, w)
}

fn toupper_raw(code: u32) -> u32 {
    if code < 0xB5 {
        if (0x61..=0x7A).contains(&code) { code - 0x20 } else { code }
    } else {
        lookup(unicode::UPPER, code).unwrap_or(code)
    }
}

fn tolower_raw(code: u32) -> u32 {
    if code < 0xC0 {
        if (0x41..=0x5A).contains(&code) { code + 0x20 } else { code }
    } else {
        lookup(unicode::LOWER, code).unwrap_or(code)
    }
}

fn totitle_raw(code: u32) -> u32 {
    lookup(unicode::TITLE, code).unwrap_or_else(|| toupper_raw(code))
}

fn tofold_raw(code: u32) -> u32 {
    if code < 0x80 {
        if (0x41..=0x5A).contains(&code) { code + 0x20 } else { code }
    } else {
        lookup(unicode::FOLD, code).unwrap_or(code)
    }
}

/// The simple mapping of a raw table value.
fn simple(raw: u32) -> u32 {
    if raw > 0xFFFFFF { unicode::EXTRA[(raw & 0xFFFFFF) as usize] } else { raw }
}

/// Writes a full mapping (`emit_special_casing_sequence`) or a code point.
fn emit(raw: u32, out: &mut [u32; 192], p: &mut usize) {
    if raw > 0xFFFFFF {
        let len = (raw >> 24) as usize;
        let at = (raw & 0xFFFFFF) as usize;
        for &w in &unicode::EXTRA[at + 1..=at + len] {
            out[*p] = w;
            *p += 1;
        }
    } else {
        out[*p] = raw;
        *p += 1;
    }
}

/// Whether the rest of the input, after the current chunk, continues with a
/// cased letter (skipping case-ignorable characters).
fn scan_ahead_for_cased(s: &[u8], mut pos: usize) -> bool {
    while pos < s.len() {
        let w = decode_one(s, &mut pos);
        if is_cased(w) {
            return true;
        }
        if !is_case_ignorable(w) {
            return false;
        }
    }
    false
}

/// `scan_back_for_cased_letter`: looks through what is left of the previous
/// chunk's converted output (`converted[begin..end]`, backwards).
fn scan_back_for_cased(converted: &[u32; 192], begin: usize, end: Option<usize>) -> bool {
    let Some(mut e) = end else { return false };
    while e > begin {
        e -= 1;
        let w = converted[e];
        if is_cased(w) {
            return true;
        }
        if !is_case_ignorable(w) {
            return false;
        }
    }
    false
}

/// Whether the capital sigma at `i` of the chunk ends a word (PHP's final
/// sigma rule, with its chunk-limited look-behind).
fn is_final_sigma(
    wbuf: &[u32],
    i: usize,
    s: &[u8],
    pos: usize,
    converted: &[u32; 192],
    p: usize,
    converted_end: Option<usize>,
) -> bool {
    let mut j = i as isize - 1;
    while j >= 0 && is_case_ignorable(wbuf[j as usize]) {
        j -= 1;
    }
    let before = if j >= 0 { is_cased(wbuf[j as usize]) } else { scan_back_for_cased(converted, p, converted_end) };
    if !before {
        return false;
    }
    let mut j = i + 1;
    while j < wbuf.len() && is_case_ignorable(wbuf[j]) {
        j += 1;
    }
    if j >= wbuf.len() { !scan_ahead_for_cased(s, pos) } else { !is_cased(wbuf[j]) }
}

/// `php_unicode_convert_case` for UTF-8 in and out, in chunks of 64 code
/// points like PHP (the final-sigma look-behind depends on them).
fn convert_case(s: &[u8], case: Case, bad: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(s.len() + 1);
    let mut converted = [0u32; 192];
    let mut converted_end: Option<usize> = None;
    let mut title_mode = false;
    let mut pos = 0;
    let mut wbuf = [0u32; 64];
    while pos < s.len() {
        let mut n = 0;
        while pos < s.len() && n < 64 {
            wbuf[n] = decode_one(s, &mut pos);
            n += 1;
        }
        let w_in = &wbuf[..n];
        let mut p = 0;
        for (i, &w) in w_in.iter().enumerate() {
            if w > 0xFFFFFF {
                converted[p] = w;
                p += 1;
                continue;
            }
            match case {
                Case::UpperSimple => {
                    converted[p] = simple(toupper_raw(w));
                    p += 1;
                }
                Case::LowerSimple => {
                    converted[p] = simple(tolower_raw(w));
                    p += 1;
                }
                Case::FoldSimple => {
                    converted[p] = simple(tofold_raw(w));
                    p += 1;
                }
                Case::TitleSimple => {
                    converted[p] = if title_mode { simple(tolower_raw(w)) } else { simple(totitle_raw(w)) };
                    p += 1;
                    if !is_case_ignorable(w) {
                        title_mode = is_cased(w);
                    }
                }
                Case::Upper => emit(toupper_raw(w), &mut converted, &mut p),
                Case::Fold => emit(tofold_raw(w), &mut converted, &mut p),
                Case::Lower => {
                    if w == 0x3A3 && is_final_sigma(w_in, i, s, pos, &converted, p, converted_end) {
                        converted[p] = 0x3C2;
                        p += 1;
                    } else {
                        emit(tolower_raw(w), &mut converted, &mut p);
                    }
                }
                Case::Title => {
                    if title_mode {
                        if w == 0x3A3 && is_final_sigma(w_in, i, s, pos, &converted, p, converted_end) {
                            converted[p] = 0x3C2;
                            p += 1;
                        } else {
                            emit(tolower_raw(w), &mut converted, &mut p);
                        }
                    } else {
                        emit(totitle_raw(w), &mut converted, &mut p);
                    }
                    if !is_case_ignorable(w) {
                        title_mode = is_cased(w);
                    }
                }
            }
        }
        converted_end = Some(p);
        for &w in &converted[..p] {
            encode(&mut out, w, bad);
        }
    }
    out
}

/// PHP `mb_convert_case($string, $mode)`. Invalid sequences become `?`.
pub fn mb_convert_case(s: &[u8], case: Case) -> Vec<u8> {
    convert_case(s, case, SUBSTITUTE)
}

/// PHP `mb_strtoupper($string)`: full upper case (`MB_CASE_UPPER`).
pub fn mb_strtoupper(s: &[u8]) -> Vec<u8> {
    convert_case(s, Case::Upper, SUBSTITUTE)
}

/// PHP `mb_strtolower($string)`: full lower case with the final sigma rule
/// (`MB_CASE_LOWER`).
pub fn mb_strtolower(s: &[u8]) -> Vec<u8> {
    convert_case(s, Case::Lower, SUBSTITUTE)
}

/// `php_mb_ulcfirst`: converts the first character with `case`; returns the
/// input unchanged when that does not change it, else the converted first
/// character and the re-encoded rest.
fn ulcfirst(s: &[u8], case: Case) -> Cow<'_, [u8]> {
    let first = get_substr(s, 0, 1);
    let head = convert_case(&first, case, SUBSTITUTE);
    if head == first {
        return Cow::Borrowed(s);
    }
    let mut out = head;
    out.extend_from_slice(&get_substr(s, 1, usize::MAX));
    Cow::Owned(out)
}

/// PHP `mb_ucfirst($string)`: title-cases the first character (full mapping).
pub fn mb_ucfirst(s: &[u8]) -> Cow<'_, [u8]> {
    ulcfirst(s, Case::Title)
}

/// PHP `mb_lcfirst($string)`: lower-cases the first character.
pub fn mb_lcfirst(s: &[u8]) -> Cow<'_, [u8]> {
    ulcfirst(s, Case::Lower)
}

