/**
 * Hand-written Reviews client: the reviews API has not shipped in a Console SDK
 * release yet, so the generated SDK carries no `Reviews` service. Keep it in step
 * with `src/Appwrite/Platform/Modules/Reviews`, and delete this folder for the
 * generated one once it ships.
 */

import type { Client } from '@appwrite.io/console'

import type {
  Review,
  ReviewList,
  ReviewRepository,
  ReviewRepositoryList,
} from './models'

export class Reviews {
  client: Client

  constructor(client: Client) {
    this.client = client
  }

  /**
   * List the code reviews of the project, without their findings.
   *
   * @param {string[]} params.queries - Queries generated by SDK Query class.
   * @param {boolean} params.total - When false, the total is not calculated.
   * @throws {AppwriteException}
   * @returns {Promise<ReviewList>}
   */
  list(
    params: { queries?: string[]; total?: boolean } = {},
  ): Promise<ReviewList> {
    const payload: Record<string, unknown> = {}
    if (typeof params.queries !== 'undefined') {
      payload['queries'] = params.queries
    }
    if (typeof params.total !== 'undefined') {
      payload['total'] = params.total
    }
    return this.client.call(
      'get',
      this.uri('/reviews'),
      this.headers(),
      payload,
    )
  }

  /**
   * Get a code review with the findings it posted.
   *
   * @param {string} params.reviewId - Review ID.
   * @throws {AppwriteException}
   * @returns {Promise<Review>}
   */
  get(params: { reviewId: string }): Promise<Review> {
    const apiPath = '/reviews/{reviewId}'.replace(
      '{reviewId}',
      encodeURIComponent(params.reviewId),
    )
    return this.client.call('get', this.uri(apiPath), this.headers(), {})
  }

  /**
   * List the repositories the project reviews pull requests for.
   *
   * @param {string[]} params.queries - Queries generated by SDK Query class.
   * @param {boolean} params.total - When false, the total is not calculated.
   * @throws {AppwriteException}
   * @returns {Promise<ReviewRepositoryList>}
   */
  listRepositories(
    params: { queries?: string[]; total?: boolean } = {},
  ): Promise<ReviewRepositoryList> {
    const payload: Record<string, unknown> = {}
    if (typeof params.queries !== 'undefined') {
      payload['queries'] = params.queries
    }
    if (typeof params.total !== 'undefined') {
      payload['total'] = params.total
    }
    return this.client.call(
      'get',
      this.uri('/reviews/repositories'),
      this.headers(),
      payload,
    )
  }

  /**
   * Turn on code review for a GitHub repository connected through an installation.
   *
   * @param {string} params.installationId - Installation ID.
   * @param {string} params.providerRepositoryId - GitHub repository ID.
   * @throws {AppwriteException}
   * @returns {Promise<ReviewRepository>}
   */
  createRepository(params: {
    installationId: string
    providerRepositoryId: string
  }): Promise<ReviewRepository> {
    return this.client.call(
      'post',
      this.uri('/reviews/repositories'),
      { ...this.headers(), 'content-type': 'application/json' },
      {
        installationId: params.installationId,
        providerRepositoryId: params.providerRepositoryId,
      },
    )
  }

  /**
   * Turn off code review for a repository. Its past reviews stay in the project.
   *
   * @param {string} params.repositoryId - Repository ID.
   * @throws {AppwriteException}
   * @returns {Promise<unknown>}
   */
  deleteRepository(params: { repositoryId: string }): Promise<unknown> {
    const apiPath = '/reviews/repositories/{repositoryId}'.replace(
      '{repositoryId}',
      encodeURIComponent(params.repositoryId),
    )
    return this.client.call(
      'delete',
      this.uri(apiPath),
      { ...this.headers(), 'content-type': 'application/json' },
      {},
    )
  }

  private uri(apiPath: string): URL {
    return new URL(this.client.config.endpoint + apiPath)
  }

  private headers(): Record<string, string> {
    return {
      'X-Appwrite-Project': this.client.config.project,
      accept: 'application/json',
    }
  }
}
