/**
 * Hand-written Reviews client: the reviews API has not shipped in a Console SDK
 * release yet, so the generated SDK carries no `Reviews` service. Keep it in step
 * with `src/Appwrite/Platform/Modules/Reviews`, and delete this folder for the
 * generated one once it ships.
 */

import type { Client } from '@appwrite.io/console'

import type {
  Review,
  ReviewAuthorList,
  ReviewAuthorRange,
  ReviewCategoryList,
  ReviewEventList,
  ReviewInstallation,
  ReviewLearningList,
  ReviewList,
  ReviewRepository,
  ReviewRepositoryList,
  ReviewStrength,
  ReviewSummary,
} from './models'

export class Reviews {
  client: Client

  constructor(client: Client) {
    this.client = client
  }

  /**
   * List the code reviews of the project, without their findings.
   *
   * @param {string[]} params.queries - Queries generated by SDK Query class.
   * @param {boolean} params.total - When false, the total is not calculated.
   * @throws {AppwriteException}
   * @returns {Promise<ReviewList>}
   */
  list(
    params: { queries?: string[]; total?: boolean } = {},
  ): Promise<ReviewList> {
    const payload: Record<string, unknown> = {}
    if (typeof params.queries !== 'undefined') {
      payload['queries'] = params.queries
    }
    if (typeof params.total !== 'undefined') {
      payload['total'] = params.total
    }
    return this.client.call(
      'get',
      this.uri('/reviews'),
      this.headers(),
      payload,
    )
  }

  /**
   * Get a code review with the findings it posted.
   *
   * @param {string} params.reviewId - Review ID.
   * @throws {AppwriteException}
   * @returns {Promise<Review>}
   */
  get(params: { reviewId: string }): Promise<Review> {
    const apiPath = '/reviews/{reviewId}'.replace(
      '{reviewId}',
      encodeURIComponent(params.reviewId),
    )
    return this.client.call('get', this.uri(apiPath), this.headers(), {})
  }

  /**
   * List the steps the review agent took during a review, oldest first.
   *
   * @param {string} params.reviewId - Review ID.
   * @param {string[]} params.queries - Queries generated by SDK Query class.
   * @throws {AppwriteException}
   * @returns {Promise<ReviewEventList>}
   */
  listEvents(params: {
    reviewId: string
    queries?: string[]
  }): Promise<ReviewEventList> {
    const apiPath = '/reviews/{reviewId}/events'.replace(
      '{reviewId}',
      encodeURIComponent(params.reviewId),
    )
    const payload: Record<string, unknown> = {}
    if (typeof params.queries !== 'undefined') {
      payload['queries'] = params.queries
    }
    return this.client.call('get', this.uri(apiPath), this.headers(), payload)
  }

  /**
   * List the repositories the project reviews pull requests for.
   *
   * @param {string[]} params.queries - Queries generated by SDK Query class.
   * @param {boolean} params.total - When false, the total is not calculated.
   * @throws {AppwriteException}
   * @returns {Promise<ReviewRepositoryList>}
   */
  listRepositories(
    params: { queries?: string[]; total?: boolean } = {},
  ): Promise<ReviewRepositoryList> {
    const payload: Record<string, unknown> = {}
    if (typeof params.queries !== 'undefined') {
      payload['queries'] = params.queries
    }
    if (typeof params.total !== 'undefined') {
      payload['total'] = params.total
    }
    return this.client.call(
      'get',
      this.uri('/reviews/repositories'),
      this.headers(),
      payload,
    )
  }

  /**
   * Turn on code review for a GitHub repository connected through an installation.
   *
   * @param {string} params.installationId - Installation ID.
   * @param {string} params.providerRepositoryId - GitHub repository ID.
   * @param {ReviewStrength} params.strength - How hard pull requests are reviewed. Defaults to normal.
   * @throws {AppwriteException}
   * @returns {Promise<ReviewRepository>}
   */
  createRepository(params: {
    installationId: string
    providerRepositoryId: string
    strength?: ReviewStrength
  }): Promise<ReviewRepository> {
    const payload: Record<string, unknown> = {
      installationId: params.installationId,
      providerRepositoryId: params.providerRepositoryId,
    }
    if (typeof params.strength !== 'undefined') {
      payload['strength'] = params.strength
    }
    return this.client.call(
      'post',
      this.uri('/reviews/repositories'),
      { ...this.headers(), 'content-type': 'application/json' },
      payload,
    )
  }

  /**
   * Change how hard a repository's pull requests are reviewed. Reviews already
   * queued keep the strength they were queued at.
   *
   * @param {string} params.repositoryId - Repository ID.
   * @param {ReviewStrength} params.strength - How hard pull requests are reviewed.
   * @throws {AppwriteException}
   * @returns {Promise<ReviewRepository>}
   */
  updateRepositoryStrength(params: {
    repositoryId: string
    strength: ReviewStrength
  }): Promise<ReviewRepository> {
    const apiPath = '/reviews/repositories/{repositoryId}/strength'.replace(
      '{repositoryId}',
      encodeURIComponent(params.repositoryId),
    )
    return this.client.call(
      'patch',
      this.uri(apiPath),
      { ...this.headers(), 'content-type': 'application/json' },
      { strength: params.strength },
    )
  }

  /**
   * Turn off code review for a repository. Its past reviews stay in the project.
   *
   * @param {string} params.repositoryId - Repository ID.
   * @throws {AppwriteException}
   * @returns {Promise<unknown>}
   */
  deleteRepository(params: { repositoryId: string }): Promise<unknown> {
    const apiPath = '/reviews/repositories/{repositoryId}'.replace(
      '{repositoryId}',
      encodeURIComponent(params.repositoryId),
    )
    return this.client.call(
      'delete',
      this.uri(apiPath),
      { ...this.headers(), 'content-type': 'application/json' },
      {},
    )
  }

  /**
   * Choose whether code review is turned on for repositories added to a GitHub
   * installation later. They are reviewed at normal strength.
   *
   * @param {string} params.installationId - Installation ID.
   * @param {boolean} params.newRepositories - Review repositories added later.
   * @throws {AppwriteException}
   * @returns {Promise<ReviewInstallation>}
   */
  updateInstallation(params: {
    installationId: string
    newRepositories: boolean
  }): Promise<ReviewInstallation> {
    const apiPath = '/reviews/installations/{installationId}'.replace(
      '{installationId}',
      encodeURIComponent(params.installationId),
    )
    return this.client.call(
      'patch',
      this.uri(apiPath),
      { ...this.headers(), 'content-type': 'application/json' },
      { newRepositories: params.newRepositories },
    )
  }

  /**
   * List what the reviewer was asked to remember in conversations on GitHub.
   *
   * @param {string[]} params.queries - Queries generated by SDK Query class.
   * @param {boolean} params.total - When false, the total is not calculated.
   * @throws {AppwriteException}
   * @returns {Promise<ReviewLearningList>}
   */
  listLearnings(
    params: { queries?: string[]; total?: boolean } = {},
  ): Promise<ReviewLearningList> {
    const payload: Record<string, unknown> = {}
    if (typeof params.queries !== 'undefined') {
      payload['queries'] = params.queries
    }
    if (typeof params.total !== 'undefined') {
      payload['total'] = params.total
    }
    return this.client.call(
      'get',
      this.uri('/reviews/learnings'),
      this.headers(),
      payload,
    )
  }

  /**
   * Delete a learning. Later reviews and answers no longer follow it.
   *
   * @param {string} params.learningId - Learning ID.
   * @throws {AppwriteException}
   * @returns {Promise<unknown>}
   */
  deleteLearning(params: { learningId: string }): Promise<unknown> {
    const apiPath = '/reviews/learnings/{learningId}'.replace(
      '{learningId}',
      encodeURIComponent(params.learningId),
    )
    return this.client.call(
      'delete',
      this.uri(apiPath),
      { ...this.headers(), 'content-type': 'application/json' },
      {},
    )
  }

  /**
   * List the authors of the project's reviewed pull requests with how their
   * pull requests fared in review, most reviewed pull requests first.
   *
   * @param {ReviewAuthorRange} params.range - Date range of the reviews. Defaults to 30d.
   * @param {string} params.repositoryId - Count only the reviews of this repository.
   * @throws {AppwriteException}
   * @returns {Promise<ReviewAuthorList>}
   */
  listAuthors(
    params: { range?: ReviewAuthorRange; repositoryId?: string } = {},
  ): Promise<ReviewAuthorList> {
    const payload: Record<string, unknown> = {}
    if (typeof params.range !== 'undefined') {
      payload['range'] = params.range
    }
    if (params.repositoryId) {
      payload['repositoryId'] = params.repositoryId
    }
    return this.client.call(
      'get',
      this.uri('/reviews/authors'),
      this.headers(),
      payload,
    )
  }

  /**
   * List the categories of the findings posted on the project's pull
   * requests with how many were fixed and how many dismissed, most dismissed
   * first.
   *
   * @param {ReviewAuthorRange} params.range - Date range of the reviews. Defaults to 30d.
   * @param {string} params.repositoryId - Count only the reviews of this repository.
   * @throws {AppwriteException}
   * @returns {Promise<ReviewCategoryList>}
   */
  listCategories(
    params: { range?: ReviewAuthorRange; repositoryId?: string } = {},
  ): Promise<ReviewCategoryList> {
    const payload: Record<string, unknown> = {}
    if (typeof params.range !== 'undefined') {
      payload['range'] = params.range
    }
    if (params.repositoryId) {
      payload['repositoryId'] = params.repositoryId
    }
    return this.client.call(
      'get',
      this.uri('/reviews/categories'),
      this.headers(),
      payload,
    )
  }

  /**
   * Get how the project's pull requests fared in review over a range and over
   * the same length of time before it, with each day of the range.
   *
   * @param {ReviewAuthorRange} params.range - Date range of the reviews: whole days, today included. Defaults to 30d.
   * @param {string} params.repositoryId - Count only the reviews of this repository.
   * @throws {AppwriteException}
   * @returns {Promise<ReviewSummary>}
   */
  getSummary(
    params: { range?: ReviewAuthorRange; repositoryId?: string } = {},
  ): Promise<ReviewSummary> {
    const payload: Record<string, unknown> = {}
    if (typeof params.range !== 'undefined') {
      payload['range'] = params.range
    }
    if (params.repositoryId) {
      payload['repositoryId'] = params.repositoryId
    }
    return this.client.call(
      'get',
      this.uri('/reviews/summary'),
      this.headers(),
      payload,
    )
  }

  private uri(apiPath: string): URL {
    return new URL(this.client.config.endpoint + apiPath)
  }

  private headers(): Record<string, string> {
    return {
      'X-Appwrite-Project': this.client.config.project,
      accept: 'application/json',
    }
  }
}
