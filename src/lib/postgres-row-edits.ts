export function groupPostgresEditsByRow(
  edits: PendingPostgresRowCellEdit[],
): Map<
  string,
  {
    identity: PendingPostgresRowCellEdit['identity']
    changes: Record<string, RowCellValue>
  }
> {
  const grouped = new Map<
    string,
    {
      identity: PendingPostgresRowCellEdit['identity']
      changes: Record<string, RowCellValue>
    }
  >()

  for (const edit of edits) {
    const existing = grouped.get(edit.rowKey)
    if (existing) {
      existing.changes[edit.columnKey] = edit.value
      continue
    }
    grouped.set(edit.rowKey, {
      identity: edit.identity,
      changes: { [edit.columnKey]: edit.value },
    })
  }

  return grouped
}
