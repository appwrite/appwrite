use Utopia\Validator\Text;
use Utopia\Validator\WhiteList;

class Create extends Action
{
    use HTTP;

    private const array EXTENSIONS = [FileExt::TYPE_PNG, FileExt::TYPE_JPG, FileExt::TYPE_JPEG];

    private const array IMAGE_TYPES = [
        FileExt::TYPE_PNG => IMAGETYPE_PNG,
        FileExt::TYPE_JPG => IMAGETYPE_JPEG,
        FileExt::TYPE_JPEG => IMAGETYPE_JPEG,
    ];

    private const int UPLOAD_TTL = 3600;

    public static function getName(): string
    {
        return 'createListingScreenshot';
    }

    public function __construct()
    {
        $this
            ->setHttpMethod(Action::HTTP_REQUEST_METHOD_POST)
            ->setHttpPath('/v1/distribution/apps/:appId/listings/:listingId/screenshots')
            ->desc('Create listing screenshot')
            ->groups(['api', 'distribution'])
            ->label('scope', 'distribution.write')
            ->label('resourceType', RESOURCE_TYPE_DISTRIBUTION_APPS)
            ->label('event', 'distributionApps.[appId].listings.[listingId].update')
            ->label('audits.event', 'distribution.listing.update')
            ->label('audits.resource', 'distributionApp/{request.appId}')
            ->label('sdk', new Method(
                namespace: 'distribution',
                group: 'listings',
                name: 'createListingScreenshot',
                description: <<<EOT
                Upload a PNG or JPEG screenshot to a store listing, sent in chunks. Once the last chunk arrives the screenshot is added after the listing's other screenshots. A screenshot is never replaced: delete it and upload a new one with another ID. A screenshot sent in more than one chunk needs a custom screenshot ID.
                EOT,
                auth: [AuthType::ADMIN, AuthType::KEY],
                responses: [
                    new SDKResponse(
                        code: Response::STATUS_CODE_CREATED,
                        model: Response::MODEL_DISTRIBUTION_LISTING,
                    )
                ],
                requestType: ContentType::MULTIPART,
                type: MethodType::UPLOAD,
                // Hidden until Distribution is generally available; preview SDK builds show it.
                hide: System::getEnv('_APP_SDK_PREVIEW', 'disabled') !== 'enabled',
            ))
            ->param('appId', '', fn (Database $dbForProject) => new UID($dbForProject->getMaxUidLength()), 'App ID.', false, ['dbForProject'])
            ->param('listingId', '', fn (Database $dbForProject) => new UID($dbForProject->getMaxUidLength()), 'Listing ID.', false, ['dbForProject'])
            ->param('screenshotId', '', fn (Database $dbForProject) => new CustomId(false, $dbForProject->getMaxUidLength()), "Screenshot ID. Choose a custom ID or generate a random ID with `ID.unique()`. A screenshot sent in more than one chunk needs a custom ID. Valid chars are a-z, A-Z, 0-9, period, hyphen, and underscore. Can't start with a special char. Max length is 36 chars.", false, ['dbForProject'])
            ->param('file', [], new File(), 'Screenshot to upload: a PNG or JPEG image of at most ' . Google::IMAGE_LIMIT . ' bytes.', skipValidation: true)
            ->param('set', '', new Text(128, 1), 'Screenshot set. On Android, the Google Play image type: ' . \implode(', ', Listings::IMAGE_TYPES) . '. On iOS, the App Store placement group the screenshot is shown in.')
            ->param('aiGeneratedState', null, new Nullable(new WhiteList(Listings::AI_GENERATED_STATES, true)), 'Whether the image was generated by AI, as attested to Google Play. Required on Android and not allowed on iOS.', true, enum: new Enum(name: 'DistributionAiGeneratedState'))
            ->inject('request')
            ->inject('response')
            ->inject('dbForProject')
            ->inject('project')
            ->inject('queueForEvents')
            ->inject('deviceForDistribution')
            ->inject('deviceForLocal')
            ->inject('locks')
            ->inject('cache')
            ->callback($this->action(...));
    }

    public function action(
        string $appId,
        string $listingId,
        string $screenshotId,
        mixed $file,
        string $set,
        ?string $aiGeneratedState,
        Request $request,
        Response $response,
        Database $dbForProject,
        Document $project,
        Event $queueForEvents,
        Device $deviceForDistribution,
        Device $deviceForLocal,
        callable $locks,
        Cache $cache,
    ): void {
        $app = $dbForProject->getDocument('distributionApps', $appId);

        if ($app->isEmpty()) {
            throw new Exception(Exception::DISTRIBUTION_APP_NOT_FOUND);
        }

        $listing = $this->getListing($dbForProject, $app, $listingId);
        $platform = Platform::from((string) $listing->getAttribute('platform'));

        $file = $request->getFiles('file');

        // GraphQL multipart spec adds files with index keys
        if (empty($file)) {
            $file = $request->getFiles(0);
        }

        if (empty($file)) {
            throw new Exception(Exception::STORAGE_FILE_EMPTY, 'No file sent');
        }

        $fileName = (\is_array($file['name']) && isset($file['name'][0])) ? $file['name'][0] : $file['name'];
        $fileTmpName = (\is_array($file['tmp_name']) && isset($file['tmp_name'][0])) ? $file['tmp_name'][0] : $file['tmp_name'];
        $fileSize = (\is_array($file['size']) && isset($file['size'][0])) ? $file['size'][0] : $file['size'];

        if (!(new FileExt(self::EXTENSIONS))->isValid($fileName)) {
            throw new Exception(Exception::STORAGE_FILE_TYPE_UNSUPPORTED, 'Only ' . \implode(', ', self::EXTENSIONS) . ' screenshots can be uploaded.');
        }

        $this->assertSet($platform, $set, $aiGeneratedState);

        $contentRange = $request->getHeaderLine('content-range');
        $chunk = 1;
        $chunks = 1;

        if ($screenshotId === 'unique()') {
            // Every chunk resends the same parameters, so a generated ID would change between chunks.
            if (!empty($contentRange)) {
                throw new Exception(Exception::GENERAL_ARGUMENT_INVALID, 'Chunked uploads need a fixed screenshot ID.');
            }

            $screenshotId = Id::unique();
        }

        if (!empty($contentRange)) {
            $start = $request->getContentRangeStart();
            $end = $request->getContentRangeEnd();
            $fileSize = $request->getContentRangeSize();
            $uploadId = $request->getHeaderLine('x-appwrite-id');

            if (\is_null($start) || \is_null($end) || \is_null($fileSize) || $start > $end || $end >= $fileSize) {
                throw new Exception(Exception::STORAGE_INVALID_CONTENT_RANGE);
            }

            // SDKs resend the ID of the first chunk's response, which is the listing's.
            if (!empty($uploadId) && $uploadId !== $listing->getId()) {
                throw new Exception(Exception::STORAGE_INVALID_APPWRITE_ID);
            }

            $chunks = (int) \ceil($fileSize / APP_LIMIT_UPLOAD_CHUNK_SIZE);
            $chunk = (int) ($start / APP_LIMIT_UPLOAD_CHUNK_SIZE) + 1;

            if ($chunk > $chunks) {
                throw new Exception(Exception::STORAGE_INVALID_CONTENT_RANGE);
            }
        }

        if (!(new FileSize(Google::IMAGE_LIMIT))->isValid($fileSize)) {
            throw new Exception(Exception::STORAGE_INVALID_FILE_SIZE, 'The screenshot exceeds the maximum size of ' . Google::IMAGE_LIMIT . ' bytes.');
        }

        if (!(new Upload())->isValid($fileTmpName)) {
            throw new Exception(Exception::STORAGE_INVALID_FILE);
        }

        $fileSize ??= $deviceForLocal->getFileSize($fileTmpName);
        $extension = \strtolower(\pathinfo($fileName, PATHINFO_EXTENSION));

        $upload = [
            'path' => Listings::path($deviceForDistribution, $listing->getId(), $screenshotId, $extension),
            'name' => $fileName,
            'size' => (int) $fileSize,
            'chunks' => $chunks,
            'set' => $set,
            'aiGeneratedState' => $aiGeneratedState,
            'metadata' => ['content_type' => $deviceForLocal->getFileMimeType($fileTmpName)],
        ];
        $key = 'distribution:listing:upload:' . $project->getId() . ':' . $listing->getId() . ':' . $screenshotId;

        try {
            $locks('distribution:listing:' . $project->getId() . ':' . $listing->getId(), 60, function () use ($app, $cache, $chunk, $dbForProject, $deviceForDistribution, $deviceForLocal, $extension, $fileTmpName, $key, $listingId, $platform, $queueForEvents, $response, $screenshotId, $upload): void {
                $listing = $this->getListing($dbForProject, $app, $listingId);
                $path = $upload['path'];

                $this->assertScreenshot($listing, $platform, $screenshotId, $upload['set']);

                // Screenshot files are immutable: a release snapshot can still point at one removed from the listing.
                if ($deviceForDistribution->exists($path)) {
                    throw new Exception(Exception::RESOURCE_ALREADY_EXISTS, 'A screenshot with this ID already exists. Choose another screenshot ID.');
                }

                $state = $cache->load($key, self::UPLOAD_TTL);

                if (!$this->isUpload($state, $upload)) {
                    if ($chunk !== 1) {
                        throw new Exception(Exception::STORAGE_INVALID_CONTENT_RANGE, 'No screenshot upload of this file is in progress for the listing.');
                    }

                    $state = $upload;
                    $deviceForDistribution->prepare($path, $state['metadata']['content_type'], $state['chunks'], $state['metadata']);
                }

                $chunks = $state['chunks'];
                $metadata = $state['metadata'];

                // Chunk writes and assembly share the lock so no request counts or assembles a partially written chunk.
                $chunksUploaded = $deviceForDistribution->upload(
                    $deviceForLocal->read($fileTmpName),
                    $path,
                    $metadata['content_type'] ?? '',
                    $chunk,
                    $chunks,
                    $metadata
                );

                if (empty($chunksUploaded)) {
                    throw new Exception(Exception::GENERAL_SERVER_ERROR, 'Failed moving file');
                }

                $chunksUploaded = \max($chunksUploaded, (int) ($metadata['chunks'] ?? 0));

                if ($chunksUploaded < $chunks) {
                    $cache->save($key, [...$state, 'metadata' => $metadata], ttl: self::UPLOAD_TTL);

                    $queueForEvents->reset();

                    $response
                        ->setStatusCode(Response::STATUS_CODE_ACCEPTED)
                        ->dynamic($listing, Response::MODEL_DISTRIBUTION_LISTING);
                    return;
                }

                $deviceForDistribution->finalize($path, $chunks, $metadata);

                try {
                    $cache->purge($key);

                    // A chunk can carry more or fewer bytes than its range announces.
                    if ($deviceForDistribution->getFileSize($path) !== $state['size']) {
                        throw new Exception(Exception::STORAGE_INVALID_CONTENT_RANGE, 'Uploaded size does not match the size announced by Content-Range.');
                    }

                    $content = (string) $deviceForDistribution->read($path);
                    $image = \getimagesizefromstring($content);

                    if ($image === false || $image[2] !== self::IMAGE_TYPES[$extension]) {
                        throw new Exception(Exception::STORAGE_FILE_TYPE_UNSUPPORTED, 'The screenshot must be a PNG or JPEG image matching its file extension.');
                    }

                    $screenshot = [
                        '$id' => $screenshotId,
                        'set' => $state['set'],
                        'path' => $path,
                        'size' => $state['size'],
                        'width' => $image[0],
                        'height' => $image[1],
                        'digest' => \hash('sha256', $content),
                    ];

                    if ($platform === Platform::Android) {
                        $screenshot['aiGeneratedState'] = $state['aiGeneratedState'];
                    }

                    $screenshots = [...$listing->getAttribute('screenshots', []), $screenshot];

                    if (\strlen(\json_encode($screenshots, JSON_THROW_ON_ERROR)) > Listings::LENGTH) {
                        throw new Exception(Exception::GENERAL_ARGUMENT_INVALID, 'The listing holds too many screenshots. Delete one before uploading another.');
                    }

                    $listing = $dbForProject->updateDocument('distributionListings', $listing->getId(), new Document([
                        'screenshots' => $screenshots,
                        'revision' => (int) $listing->getAttribute('revision', 0) + 1,
                    ]));
                } catch (\Throwable $error) {
                    $deviceForDistribution->delete($path);

                    throw $error;
                }

                $queueForEvents
                    ->setParam('appId', $app->getId())
                    ->setParam('listingId', $listing->getId());

                $response
                    ->setStatusCode(Response::STATUS_CODE_CREATED)
                    ->dynamic($listing, Response::MODEL_DISTRIBUTION_LISTING);
            }, timeout: 10.0);
        } catch (Contention) {
            $response->addHeader('Retry-After', '5');
            throw new Exception(Exception::GENERAL_RATE_LIMIT_EXCEEDED, 'Listing is busy. Try again.');
        }
    }

    private function getListing(Database $dbForProject, Document $app, string $listingId): Document
    {
        $listing = $dbForProject->getDocument('distributionListings', $listingId);

        if ($listing->isEmpty() || $listing->getAttribute('appInternalId') !== $app->getSequence()) {
            throw new Exception(Exception::DISTRIBUTION_LISTING_NOT_FOUND);
        }

        return $listing;
    }

    private function assertSet(Platform $platform, string $set, ?string $aiGeneratedState): void
    {
        if ($platform === Platform::Ios) {
            if (!\is_null($aiGeneratedState)) {
                throw new Exception(Exception::GENERAL_ARGUMENT_INVALID, 'Only Android screenshots carry an AI-generated state.');
            }

            return;
        }

        if (!\in_array($set, Listings::IMAGE_TYPES, true)) {
            throw new Exception(Exception::GENERAL_ARGUMENT_INVALID, 'An Android screenshot set must be one of: ' . \implode(', ', Listings::IMAGE_TYPES) . '.');
        }

        if (\is_null($aiGeneratedState)) {
            throw new Exception(Exception::GENERAL_ARGUMENT_INVALID, 'Android screenshots need an AI-generated state, one of: ' . \implode(', ', Listings::AI_GENERATED_STATES) . '.');
        }
    }

    private function assertScreenshot(Document $listing, Platform $platform, string $screenshotId, string $set): void
    {
        foreach ($listing->getAttribute('screenshots', []) as $screenshot) {
            if (($screenshot['$id'] ?? null) === $screenshotId) {
                throw new Exception(Exception::RESOURCE_ALREADY_EXISTS, 'A screenshot with this ID already exists. Choose another screenshot ID.');
            }

            if (
                $platform === Platform::Android
                && \in_array($set, Listings::SINGLE_IMAGE_TYPES, true)
                && ($screenshot['set'] ?? null) === $set
            ) {
                throw new Exception(Exception::GENERAL_ARGUMENT_INVALID, "The {$set} set holds a single image. Delete the current one first.");
            }
        }
    }

    /**
     * @param array{path: string, name: string, size: int, chunks: int, set: string, aiGeneratedState: ?string, metadata: array<string, mixed>} $upload
     * @phpstan-assert-if-true array{path: string, name: string, size: int, chunks: int, set: string, aiGeneratedState: ?string, metadata: array<string, mixed>} $state
     */
    private function isUpload(mixed $state, array $upload): bool
    {
        if (!\is_array($state) || !\is_array($state['metadata'] ?? null)) {
            return false;
        }

        foreach (['path', 'size', 'chunks', 'set', 'aiGeneratedState'] as $attribute) {
            if (($state[$attribute] ?? null) !== $upload[$attribute]) {
                return false;
            }
        }

        return true;
    }
}
